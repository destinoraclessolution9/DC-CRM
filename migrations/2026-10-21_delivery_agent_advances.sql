-- ═══════════════════════════════════════════════════════════════════════════
-- Agent stock advances (2026-10-21)
--
-- An agent sometimes hands the customer a piece from the AGENT'S OWN stock
-- (bought earlier with their own money) because the office piece has not
-- arrived. The customer's handover is done as normal; the office owes the
-- agent the same piece back, item for item, when it arrives.
--   · only Calligraphy / Artistic Masterpieces / 财库·财托 (rings + Feng Shui are
--     made for the person — never lent)
--   · one advance per delivery item; any agent can lend for any customer
--   · the LENDER ticks "returned to me" (photo optional); admin can close too
--   · reminders to the lender and the sale's agent on the expected-back date,
--     then weekly while still owed; "↩ collect your stock back" on the 📋 top 5
--   · no change to the sale, credit or commission — a stock IOU only
-- ═══════════════════════════════════════════════════════════════════════════

-- Product groups that can be lent
create or replace function public.delivery_advance_allowed(p_item text) returns boolean
language sql stable security definer set search_path = public as $$
    select not public.journey_is_ring(p_item)
       and coalesce(public.journey_item_group(p_item), '') not like 'Fengshui%'
       and (coalesce(public.journey_item_group(p_item), '') in ('Calligraphy Adornment', 'Artistic Masterpieces', 'Royal Woodwork Series')
            or exists (select 1 from public.products pr
                        where pr.subcategory in ('Calligraphy Adornment', 'Artistic Masterpieces', 'Royal Woodwork Series')
                          and coalesce(pr.is_active, true) and public.pipeline_name_match(p_item, pr.name)))
$$;

create table if not exists public.delivery_advances (
    id               bigint generated by default as identity primary key,
    delivery_item_id bigint not null unique references public.delivery_items(id) on delete cascade,
    customer_id      bigint references public.customers(id) on delete set null,
    lender_agent_id  bigint not null,
    sale_agent_id    bigint,
    item_name        text not null,
    given_date       date not null,
    expected_back    date,
    status           text not null default 'owed' check (status in ('owed', 'returned')),
    returned_date    date,
    return_photos    jsonb not null default '[]'::jsonb,
    note             text,
    returned_by      bigint,
    created_by       bigint,
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),
    check (status <> 'returned' or returned_date is not null)
);
create index if not exists delivery_adv_lender on public.delivery_advances (lender_agent_id) where status = 'owed';

-- Fill / guard on insert: the item must be lendable and already handed over.
create or replace function public.delivery_advance_fill() returns trigger
language plpgsql security definer set search_path = public as $$
declare di record; pu record; prof record;
begin
    select * into di from public.delivery_items where id = new.delivery_item_id;
    if di.id is null then raise exception 'Delivery item not found'; end if;
    if tg_op = 'INSERT' then
        if not public.delivery_advance_allowed(di.item_name) then
            raise exception 'Only calligraphy, artistic masterpieces and 财库/财托 can come from an agent''s own stock';
        end if;
        if di.status = 'pending' then
            raise exception 'Hand the item over to the customer first';
        end if;
        select * into pu from public.purchases where id = di.purchase_id;
        new.customer_id   := di.customer_id;
        new.item_name     := di.item_name;
        new.given_date    := coalesce(new.given_date, di.handover_date);
        new.sale_agent_id := coalesce(new.sale_agent_id, pu.agent_id,
                                      (select responsible_agent_id from public.customers where id = di.customer_id));
        -- the office piece should arrive when the order would have been ready
        if new.expected_back is null then
            prof := public.journey_item_profile(di.item_name);
            new.expected_back := coalesce(di.expected_ready_date,
                                          (coalesce(pu.date, new.given_date) + coalesce(prof.lead_days, 120)));
        end if;
        new.created_by := coalesce(new.created_by, public.current_user_row_id());
    end if;
    if tg_op = 'UPDATE' and new.status = 'returned' and old.status = 'owed' then
        new.returned_by := coalesce(public.current_user_row_id(), new.returned_by);
    end if;
    if new.status = 'owed' then new.returned_date := null; end if;
    new.updated_at := now();
    return new;
end $$;
drop trigger if exists trg_delivery_advance_fill on public.delivery_advances;
create trigger trg_delivery_advance_fill before insert or update on public.delivery_advances
    for each row execute function public.delivery_advance_fill();

-- Undoing the customer handover removes an advance that was not returned yet.
create or replace function public.delivery_advance_undo_trg() returns trigger
language plpgsql security definer set search_path = public as $$
begin
    if new.status = 'pending' and old.status <> 'pending' then
        delete from public.delivery_advances where delivery_item_id = new.id and status = 'owed';
    end if;
    return null;
end $$;
drop trigger if exists trg_delivery_advance_undo on public.delivery_items;
create trigger trg_delivery_advance_undo after update of status on public.delivery_items
    for each row execute function public.delivery_advance_undo_trg();

alter table public.delivery_advances enable row level security;
drop policy if exists delivery_adv_sel on public.delivery_advances;
create policy delivery_adv_sel on public.delivery_advances for select to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or lender_agent_id = public.current_user_row_id() or sale_agent_id = public.current_user_row_id()
    or lender_agent_id in (select public.current_user_visible_ids())
    or sale_agent_id in (select public.current_user_visible_ids())
    or public.customer_is_visible(customer_id));
-- recording: any staff member who can see that customer (lender may be outside their team)
drop policy if exists delivery_adv_ins on public.delivery_advances;
create policy delivery_adv_ins on public.delivery_advances for insert to authenticated with check (
    coalesce(public.current_user_level(), 99) <= 12
    and (coalesce(public.current_user_level(), 99) <= 2 or public.customer_is_visible(customer_id)
         or exists (select 1 from public.delivery_items di where di.id = delivery_item_id and public.customer_is_visible(di.customer_id))));
-- ticking returned: the lender (their own stock) or admin
drop policy if exists delivery_adv_upd on public.delivery_advances;
create policy delivery_adv_upd on public.delivery_advances for update to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2 or lender_agent_id = public.current_user_row_id())
    with check (coalesce(public.current_user_level(), 99) <= 2 or lender_agent_id = public.current_user_row_id());
-- removing a wrongly-recorded advance (not yet returned): admin, the lender or who recorded it
drop policy if exists delivery_adv_del on public.delivery_advances;
create policy delivery_adv_del on public.delivery_advances for delete to authenticated using (
    status = 'owed' and (coalesce(public.current_user_level(), 99) <= 2
        or lender_agent_id = public.current_user_row_id() or created_by = public.current_user_row_id()));
grant select, insert, update, delete on public.delivery_advances to authenticated;

-- Which of these delivery items may come from an agent's stock (for the screen)
create or replace function public.delivery_advance_eligible(p_item_ids bigint[]) returns setof bigint
language sql stable security definer set search_path = public as $$
    select di.id from public.delivery_items di
     where di.id = any (p_item_ids) and public.delivery_advance_allowed(di.item_name)
$$;
revoke all on function public.delivery_advance_eligible(bigint[]) from public, anon;
grant execute on function public.delivery_advance_eligible(bigint[]) to authenticated;

-- Reminders: on the expected-back day, then every 7 days while still owed.
-- To the lender, and to the sale's agent when someone else lent the piece.
create or replace function public.queue_advance_reminders() returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date; v_n int;
begin
    insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
    select x.uid, 'advance_due', 'normal',
           case when x.uid = a.lender_agent_id then '↩ Collect your stock back' else '↩ Return stock to ' || coalesce(l.full_name, 'the agent') end,
           left(a.item_name, 40) || ' · lent to ' || coalesce(c.full_name, 'customer') || ' on ' || to_char(a.given_date, 'FMDD Mon')
             || case when v_today > a.expected_back then ' · ' || (v_today - a.expected_back) || ' days late' else ' · office piece due today' end,
           './index.html?delivery=1#customers',
           'advance_due:' || a.id || ':' || x.uid || ':' || v_today, now()
      from public.delivery_advances a
      left join public.customers c on c.id = a.customer_id
      left join public.users l on l.id = a.lender_agent_id
      cross join lateral (select a.lender_agent_id uid
                          union select a.sale_agent_id where a.sale_agent_id is not null and a.sale_agent_id <> a.lender_agent_id) x
     where a.status = 'owed' and a.expected_back is not null
       and v_today >= a.expected_back and (v_today - a.expected_back) % 7 = 0
    on conflict (user_id, dedupe_key) do nothing;
    get diagnostics v_n = row_count;
    return v_n;
end $$;
revoke all on function public.queue_advance_reminders() from public, anon, authenticated;
select cron.unschedule('advance-reminders') where exists (select 1 from cron.job where jobname = 'advance-reminders');
select cron.schedule('advance-reminders', '5 1 * * *', 'select public.queue_advance_reminders();');

-- ── 📋 top 5: "↩ collect your stock back" (redefines the to-do function) ──
create or replace function public.journey_todo_for(p_uid bigint, p_limit integer default 5)
returns table (kind text, icon text, prospect_id bigint, customer_id bigint, name text, why text, rm numeric, due date, score numeric, ref_id bigint)
language sql stable security definer set search_path = public as $$
with t as (select public.journey_today() d),
c as (   -- ① collections: ready ≤ 7 days, not handed over
    select 'collect'::text kind, '📦'::text icon, cu.converted_from_prospect_id pid, cu.id cid, cu.full_name nm,
           case when di.expected_ready_date < t.d then 'Collect ' || left(di.item_name, 30) || ' · ready since ' || to_char(di.expected_ready_date, 'FMDD Mon')
                else 'Ready ' || to_char(di.expected_ready_date, 'FMDD Mon') || ' · book the collection + photo' end why,
           coalesce(pu.amount, 10000) rm, di.expected_ready_date due,
           greatest(coalesce(pu.amount, 10000), 3000) * case when di.expected_ready_date < t.d then 3 else 2 end
             * (1 + least(greatest(t.d - di.expected_ready_date, 0), 30) / 30.0) sc, di.purchase_id ref
      from public.delivery_items di cross join t
      join public.customers cu on cu.id = di.customer_id
      left join public.purchases pu on pu.id = di.purchase_id
     where di.status = 'pending' and di.expected_ready_date <= t.d + 7
       and di.expected_ready_date >= t.d - 120
       and coalesce(pu.agent_id, cu.responsible_agent_id) = p_uid
),
g as (   -- ② Golden Road session due
    select 'gr', '🟣', coalesce(tp.prospect_id, cu.converted_from_prospect_id), tp.customer_id, coalesce(cu.full_name, pr.full_name),
           'Golden Road ' || tp.seq || '/' || tp.seq_total || case when tp.due_date < t.d then ' · overdue' else ' · due ' || to_char(tp.due_date, 'FMDD Mon') end,
           coalesce(pu.amount, 10000), tp.due_date,
           greatest(coalesce(pu.amount, 10000), 3000) * 2 * (1 + least(greatest(t.d - tp.due_date, 0), 30) / 30.0), tp.purchase_id
      from public.journey_touchpoints tp cross join t
      left join public.customers cu on cu.id = tp.customer_id
      left join public.prospects pr on pr.id = tp.prospect_id
      left join public.purchases pu on pu.id = tp.purchase_id
     where tp.status = 'pending' and tp.seq is not null and tp.assigned_to_id = p_uid and tp.due_date <= t.d + 3
       and coalesce(tp.snooze_until, t.d) <= t.d
),
cps as ( -- ③ CPS with no 2nd meeting (A)
    select 'cps', '🆕', p.id, null::bigint, p.full_name,
           'CPS ' || to_char(x.d, 'FMDD Mon') || ' · no 2nd meeting booked',
           coalesce(nullif(p.open_potential_rm, 0), 5000), x.d,
           greatest(coalesce(p.open_potential_rm, 0), 5000) * 1.5 * case when t.d - x.d <= 14 then 1.2 else 0.8 end, null::bigint
      from public.prospects p cross join t
      cross join lateral (select max(a.activity_date) d from public.activities a where a.prospect_id = p.id and a.activity_type = 'CPS') x
     where p.responsible_agent_id = p_uid and x.d between t.d - 30 and t.d - 1
       and coalesce(p.status, '') not in ('converted', 'lost') and not coalesce(p.unable_to_serve, false)
       and coalesce(p.manual_grade, '') <> 'F' and coalesce(p.cps_next_step, '') <> 'not_interested'
       and not exists (select 1 from public.activities a where a.prospect_id = p.id and a.activity_date > x.d
                         and a.activity_type in ('CPS', 'FTF', 'FSA', 'SITE', 'GR', 'EVENT', 'EVENT_CLOSING'))
       and not exists (select 1 from public.event_attendees ea where ea.attendee_type = 'prospect' and ea.entity_id = p.id
                         and ea.created_at::date >= x.d)
),
hot as ( -- ④ Commit / Audit / Hot with nothing booked
    select 'book', case p.potential_tier when 'commit' then '🟢' when 'audit' then '🩺' else '🔥' end, p.id, null::bigint, p.full_name,
           initcap(p.potential_tier) || ' · RM' || round(p.open_potential_rm / 1000) || 'k · nothing booked'
             || coalesce(' · met ' || to_char(p.potential_last_met, 'FMDD Mon'), ''),
           p.open_potential_rm, p.potential_last_met,
           p.open_potential_rm * case p.potential_tier when 'commit' then 3 when 'audit' then 2 else 1.5 end
             * (1 + least(coalesce(t.d - p.potential_last_met, 60), 60) / 60.0), null::bigint
      from public.prospects p cross join t
     where p.responsible_agent_id = p_uid and p.potential_tier in ('commit', 'audit', 'hot')
       and p.potential_next_booked is null and p.open_potential_rm > 0
),
tp as (  -- ⑤ any other journey step due today or overdue
    select 'touch', '🧭', coalesce(j.prospect_id, cu.converted_from_prospect_id), j.customer_id, coalesce(cu.full_name, pr.full_name),
           regexp_replace(j.title, '^\S+\s+', '') || case when j.due_date < t.d then ' · overdue' else '' end,
           coalesce(nullif(pr.open_potential_rm, 0), 3000), j.due_date,
           greatest(coalesce(pr.open_potential_rm, 0), 3000) * case when j.priority = 'high' then 1.2 else 1 end
             * (1 + least(greatest(t.d - j.due_date, 0), 30) / 30.0), j.id
      from public.journey_touchpoints j cross join t
      left join public.customers cu on cu.id = j.customer_id
      left join public.prospects pr on pr.id = j.prospect_id
     where j.status = 'pending' and j.seq is null and j.assigned_to_id = p_uid and j.due_date <= t.d
       and j.due_date >= t.d - 60 and coalesce(j.snooze_until, t.d) <= t.d
),
pop as ( -- ⑥ POP card charge failed / overdue a week
    select 'pop', '💳', cu.converted_from_prospect_id, cu.id, cu.full_name,
           'POP ' || i.seq || '/' || x.n || ' ' || case when i.status = 'failed' then 'charge failed' else 'overdue since ' || to_char(i.due_date, 'FMDD Mon') end
             || ' · RM' || round(i.amount) || ' — update the card / collect',
           x.left_rm, i.due_date,
           greatest(x.left_rm, 3000) * 2.5 * (1 + least(greatest(t.d - i.due_date, 0), 60) / 60.0), i.purchase_id
      from public.pop_installments i cross join t
      join public.customers cu on cu.id = i.customer_id
      cross join lateral (select count(*) n, coalesce(sum(j.amount) filter (where j.status in ('due', 'failed')), 0) left_rm
                            from public.pop_installments j where j.purchase_id = i.purchase_id) x
     where i.agent_id = p_uid and (i.status = 'failed' or (i.status = 'due' and i.due_date < t.d - 7))
),
adv as ( -- ⑦ my own stock lent to a customer: office piece due → collect it back
    select 'advance', '↩', cu.converted_from_prospect_id, cu.id, cu.full_name,
           'Collect your ' || left(a.item_name, 24) || ' back · lent ' || to_char(a.given_date, 'FMDD Mon')
             || case when a.expected_back < t.d then ' · ' || (t.d - a.expected_back) || ' days late' else ' · office piece due' end,
           coalesce(pu.amount, 5000), a.expected_back,
           greatest(coalesce(pu.amount, 5000), 3000) * 1.5 * (1 + least(greatest(t.d - a.expected_back, 0), 60) / 60.0), a.id
      from public.delivery_advances a cross join t
      join public.customers cu on cu.id = a.customer_id
      left join public.delivery_items di on di.id = a.delivery_item_id
      left join public.purchases pu on pu.id = di.purchase_id
     where a.lender_agent_id = p_uid and a.status = 'owed' and a.expected_back <= t.d + 3
),
allx as (select * from c union all select * from g union all select * from cps union all select * from hot union all select * from tp union all select * from pop union all select * from adv),
best as (
    select distinct on (coalesce('c' || cid::text, 'p' || pid::text)) * from allx
     where nm is not null
     order by coalesce('c' || cid::text, 'p' || pid::text), sc desc
)
select kind, icon, pid, cid, nm, why, rm, due, round(sc), ref from best order by sc desc limit greatest(coalesce(p_limit, 5), 1)
$$;
revoke all on function public.journey_todo_for(bigint, integer) from public, anon, authenticated;
revoke all on function public.journey_todo_for(bigint, integer) from public, anon, authenticated;
