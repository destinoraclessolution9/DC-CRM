-- Class waiting list (2026-10-26, owner).
--
-- A next step "Event invite" can name a CLASS (event category, e.g.
-- 个人风水基础课) when no session of it is on the calendar yet. The person then
-- waits for that class — no task, so nobody is nagged about a class that does
-- not exist. When a session whose topic carries that category is added to the
-- calendar:
--   * the recommending agent gets ONE task per person ("🎟️ Invite to <session>")
--     and one phone notification per session,
--   * the event screen lists them under "Recommended to attend" with Invite.
-- Registering the person for a matching session marks them invited (and closes
-- the task); ticking attended marks them attended. Waiting expires after 6 months.
-- Everything runs in triggers / SECURITY DEFINER functions that swallow their
-- errors — a waiting-list problem must never block saving a meeting or event.

create table if not exists public.class_waitlist (
    id                  bigint generated by default as identity primary key,
    prospect_id         bigint references public.prospects(id) on delete cascade,
    customer_id         bigint references public.customers(id) on delete cascade,
    category            text not null,
    recommended_by      bigint references public.users(id),
    source_activity_id  bigint,
    source_attendee_id  bigint,
    source_seq          integer,
    status              text not null default 'waiting'
                        check (status in ('waiting', 'invited', 'attended', 'dropped', 'expired')),
    invited_activity_id bigint,
    invited_at          timestamptz,
    attended_at         timestamptz,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),
    constraint class_waitlist_person check ((prospect_id is not null) <> (customer_id is not null))
);
create unique index if not exists cw_one_waiting on public.class_waitlist (coalesce(prospect_id, 0), coalesce(customer_id, 0), category) where status = 'waiting';
create index if not exists cw_waiting_cat on public.class_waitlist (category) where status = 'waiting';
create index if not exists cw_prospect on public.class_waitlist (prospect_id) where prospect_id is not null;
create index if not exists cw_customer on public.class_waitlist (customer_id) where customer_id is not null;

alter table public.class_waitlist enable row level security;
drop policy if exists class_waitlist_sel on public.class_waitlist;
create policy class_waitlist_sel on public.class_waitlist for select to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2 or recommended_by = public.current_user_row_id()
    or public.prospect_is_visible(prospect_id) or public.customer_is_visible(customer_id));
grant select on public.class_waitlist to authenticated;

alter table public.journey_touchpoints add column if not exists source_interest_id bigint;
create index if not exists jt_interest on public.journey_touchpoints (source_interest_id) where source_interest_id is not null;

-- ── Category matching ───────────────────────────────────────────────────────
-- "汇聚-专案" / "汇集专案-Condo" / "汇集 - 灵活" all compare after this.
create or replace function public.class_cat_norm(p text) returns text
language sql immutable set search_path = public as $$
    select lower(regexp_replace(replace(coalesce(p, ''), '汇聚', '汇集'), '[\s\-–—_()（）·、,，]+', '', 'g'))
$$;
-- A session matches a waiting class when one of its topic's categories is the
-- class, or a more specific one (汇集-灵活 → 汇集灵活-Condo).
create or replace function public.class_cat_match(p_wait text, p_cats text[]) returns boolean
language sql immutable set search_path = public as $$
    select exists (select 1 from unnest(coalesce(p_cats, '{}')) c
                    where public.class_cat_norm(c) <> ''
                      and public.class_cat_norm(c) like public.class_cat_norm(p_wait) || '%')
$$;
-- events.categories is JSON text ('["a","b"]') or older comma text.
create or replace function public.event_cats(p_event_id bigint) returns text[]
language plpgsql stable security definer set search_path = public as $$
declare v text; r text[];
begin
    select categories::text into v from public.events where id = p_event_id;
    if v is null or btrim(v) = '' then return '{}'; end if;
    begin
        select array_agg(x) into r from jsonb_array_elements_text(v::jsonb) x;
    exception when others then
        select array_agg(btrim(x)) into r from unnest(string_to_array(v, ',')) x where btrim(x) <> '';
    end;
    return coalesce(r, '{}');
end $$;

-- ── One invite task for one waiting entry and one session ───────────────────
create or replace function public.class_wait_task(p_entry bigint, p_session bigint) returns boolean
language plpgsql security definer set search_path = public as $$
declare e public.class_waitlist%rowtype; s record; v_today date := public.journey_today();
begin
    select * into e from public.class_waitlist where id = p_entry and status = 'waiting';
    if e.id is null then return false; end if;
    if exists (select 1 from public.journey_touchpoints t where t.source_interest_id = e.id
                and t.status in ('pending', 'overdue', 'snoozed')) then return false; end if;
    select a.id, a.activity_title, a.activity_date into s from public.activities a where a.id = p_session;
    if s.id is null then return false; end if;
    insert into public.journey_touchpoints
        (prospect_id, customer_id, stage_name, track, touchpoint_type, title, due_date, priority, status,
         assigned_to, assigned_to_id, follow_mode, auto_created, source_kind, source_interest_id)
    values (e.prospect_id, e.customer_id, 'class_invite', 'active', 'task',
            left('🎟️ Invite to ' || coalesce(nullif(btrim(s.activity_title), ''), e.category) || ' · ' || to_char(s.activity_date, 'FMDD Mon'), 200),
            greatest(v_today, s.activity_date - 3), 'high', 'pending',
            public.task_agent_uuid(e.recommended_by), e.recommended_by, 'active', true, 'class_wait', e.id);
    return true;
end $$;

-- Waiting entries for a session's classes (not expired, not already registered).
create or replace function public.class_wait_entries_for(p_session bigint)
returns setof public.class_waitlist language sql stable security definer set search_path = public as $$
    select w.* from public.class_waitlist w
      join public.activities a on a.id = p_session
     where w.status = 'waiting' and w.created_at >= now() - interval '6 months'
       and public.class_cat_match(w.category, public.event_cats(a.event_id))
       and not exists (select 1 from public.event_attendees ea
                        where ea.activity_id = p_session
                          and ((w.prospect_id is not null and ea.attendee_type = 'prospect' and ea.entity_id = w.prospect_id)
                            or (w.customer_id is not null and ea.attendee_type = 'customer' and ea.entity_id = w.customer_id)))
$$;

-- ── A session is added / moved → tasks + one notification per agent ─────────
create or replace function public.class_wait_session_trg() returns trigger
language plpgsql security definer set search_path = public as $$
declare r record; v_cats text[]; v_n int;
begin
    if new.activity_type <> 'EVENT' or new.event_id is null or new.activity_date < public.journey_today() then return null; end if;
    if new.activity_title ~ '代理会议' then return null; end if;
    v_cats := public.event_cats(new.event_id);
    if coalesce(array_length(v_cats, 1), 0) = 0 then return null; end if;
    for r in select * from public.class_wait_entries_for(new.id) loop
        perform public.class_wait_task(r.id, new.id);
    end loop;
    insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
    select w.recommended_by, 'class_wait', 'normal',
           '🎟️ ' || count(*) || ' of your people ' || case when count(*) = 1 then 'is' else 'are' end || ' waiting for ' || min(w.category),
           left('New session: ' || coalesce(new.activity_title, '') || ' · ' || to_char(new.activity_date, 'FMDD Mon')
                || ' — ' || string_agg(coalesce(p.full_name, c.full_name, ''), ', ') || '. Invite them from Next up.', 220),
           './index.html', 'class_wait:' || new.id, now()
      from public.class_wait_entries_for(new.id) w
      left join public.prospects p on p.id = w.prospect_id
      left join public.customers c on c.id = w.customer_id
     where w.recommended_by is not null
     group by w.recommended_by
    on conflict (user_id, dedupe_key) do nothing;
    return null;
exception when others then
    return null;
end $$;
drop trigger if exists trg_class_wait_session on public.activities;
create trigger trg_class_wait_session after insert or update of event_id, activity_date on public.activities
    for each row execute function public.class_wait_session_trg();

-- ── Registered / attended → the waiting entry moves on ──────────────────────
create or replace function public.class_wait_attendee_trg() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_cats text[]; v_pid bigint; v_cid bigint; v_went boolean;
begin
    if new.attendee_type = 'prospect' then v_pid := new.entity_id;
    elsif new.attendee_type = 'customer' then v_cid := new.entity_id;
    else return null; end if;
    select public.event_cats(a.event_id) into v_cats from public.activities a where a.id = new.activity_id;
    v_went := coalesce(new.attended, false) or new.attendance_status in ('Attended', 'Late');
    -- registered for a matching session → invited (task done)
    update public.journey_touchpoints t set status = 'done', completed_at = now(), updated_at = now()
     where t.source_interest_id in (
            select w.id from public.class_waitlist w
             where w.status = 'waiting' and (w.prospect_id = v_pid or w.customer_id = v_cid)
               and public.class_cat_match(w.category, v_cats))
       and t.status in ('pending', 'overdue', 'snoozed');
    update public.class_waitlist w set status = 'invited', invited_activity_id = new.activity_id, invited_at = now(), updated_at = now()
     where w.status = 'waiting' and (w.prospect_id = v_pid or w.customer_id = v_cid)
       and public.class_cat_match(w.category, v_cats);
    -- went → attended
    if v_went then
        update public.class_waitlist w set status = 'attended', attended_at = now(), updated_at = now()
         where w.status = 'invited' and w.invited_activity_id = new.activity_id
           and (w.prospect_id = v_pid or w.customer_id = v_cid);
    end if;
    return null;
exception when others then
    return null;
end $$;
drop trigger if exists trg_class_wait_attendee on public.event_attendees;
create trigger trg_class_wait_attendee after insert or update of attended, attendance_status on public.event_attendees
    for each row execute function public.class_wait_attendee_trg();

-- ── Next steps → waiting entries (extends the 2026-10-26 step sync) ─────────
-- A step {type:'event', event_category:'…'} with no session waits; it makes no
-- task. Any matching session already upcoming gets its invite task right away.
create or replace function public.class_wait_sync_rows(
    p_src text, p_src_id bigint, p_pid bigint, p_cid bigint, p_rows jsonb, p_agent bigint)
returns void language plpgsql security definer set search_path = public as $$
declare i int; v_n int := 0; v_row jsonb; v_cat text; v_keep text[] := '{}'; v_id bigint; s record;
begin
    if p_pid is null and p_cid is null then return; end if;
    if jsonb_typeof(p_rows) = 'array' then v_n := jsonb_array_length(p_rows); end if;
    for i in 1 .. v_n loop
        v_row := p_rows -> (i - 1);
        v_cat := nullif(btrim(coalesce(v_row ->> 'event_category', '')), '');
        continue when v_cat is null or (v_row ->> 'type') <> 'event' or nullif(v_row ->> 'event_activity_id', '') is not null;
        v_keep := v_keep || v_cat;
        v_id := null;
        insert into public.class_waitlist (prospect_id, customer_id, category, recommended_by, source_activity_id, source_attendee_id, source_seq)
        values (case when p_cid is null then p_pid end, p_cid, v_cat, p_agent,
                case when p_src = 'activity' then p_src_id end, case when p_src = 'attendee' then p_src_id end, i)
        on conflict (coalesce(prospect_id, 0), coalesce(customer_id, 0), category) where status = 'waiting' do nothing
        returning id into v_id;
        if v_id is not null then
            for s in select a.id from public.activities a
                      where a.activity_type = 'EVENT' and a.event_id is not null and a.activity_date >= public.journey_today()
                        and a.activity_title !~ '代理会议'
                        and public.class_cat_match(v_cat, public.event_cats(a.event_id))
                      order by a.activity_date limit 1 loop
                perform public.class_wait_task(v_id, s.id);
            end loop;
        end if;
    end loop;
    -- a class removed from this meeting's steps → stop waiting for it
    update public.class_waitlist w set status = 'dropped', updated_at = now()
     where w.status = 'waiting' and not (w.category = any (v_keep))
       and ((p_src = 'activity' and w.source_activity_id = p_src_id) or (p_src = 'attendee' and w.source_attendee_id = p_src_id));
    update public.journey_touchpoints t set status = 'skipped', updated_at = now()
     where t.status in ('pending', 'overdue', 'snoozed')
       and t.source_interest_id in (select id from public.class_waitlist where status = 'dropped'
                                     and ((p_src = 'activity' and source_activity_id = p_src_id) or (p_src = 'attendee' and source_attendee_id = p_src_id)));
end $$;
revoke execute on function public.class_wait_sync_rows(text, bigint, bigint, bigint, jsonb, bigint) from public, anon, authenticated;

-- Class-waiting rows must not become plain tasks: task_sync_rows treats a
-- step with event_category and no session as text-less (no task), and the
-- waiting list takes it from there.
create or replace function public.task_sync_rows(
    p_src text, p_src_id bigint, p_pid bigint, p_cid bigint, p_rows jsonb, p_old jsonb,
    p_meet_date date, p_agent bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
    v_today date := public.journey_today();
    v_n int := 0;
    v_row jsonb; v_old jsonb; v_title text; v_due date; v_old_due date; v_type text;
    v_tp public.journey_touchpoints%rowtype;
    i int;
begin
    if p_pid is null and p_cid is null then return; end if;
    if jsonb_typeof(p_rows) = 'array' then v_n := jsonb_array_length(p_rows); end if;
    for i in 1 .. v_n loop
        v_row := p_rows -> (i - 1);
        v_old := case when jsonb_typeof(p_old) = 'array' then p_old -> (i - 1) end;
        v_title := public.task_step_title(v_row ->> 'type', v_row ->> 'text');
        if (v_row ->> 'type') = 'event' and nullif(v_row ->> 'event_category', '') is not null
           and nullif(v_row ->> 'event_activity_id', '') is null then
            v_title := null;   -- waiting for a class: the waiting list, not a task
        end if;
        v_type := public.task_step_type(v_row ->> 'type');
        begin v_due := nullif(v_row ->> 'due', '')::date; exception when others then v_due := null; end;
        begin v_old_due := nullif(v_old ->> 'due', '')::date; exception when others then v_old_due := null; end;
        if p_src = 'activity' then
            select * into v_tp from public.journey_touchpoints where source_activity_id = p_src_id and source_seq = i;
        else
            select * into v_tp from public.journey_touchpoints where source_attendee_id = p_src_id and source_seq = i;
        end if;
        if v_title is null then
            if v_tp.id is not null and v_tp.status in ('pending', 'overdue', 'snoozed') then
                delete from public.journey_touchpoints where id = v_tp.id;
            end if;
            continue;
        end if;
        if v_tp.id is null then
            insert into public.journey_touchpoints
                (prospect_id, customer_id, stage_name, track, touchpoint_type, title, due_date, priority, status,
                 assigned_to, assigned_to_id, follow_mode, auto_created, source_kind,
                 source_activity_id, source_attendee_id, source_seq)
            values (case when p_cid is null then p_pid end, p_cid, 'follow_up', 'active', v_type, v_title,
                    coalesce(v_due, greatest(coalesce(p_meet_date, v_today) + 7, v_today)), 'med', 'pending',
                    public.task_agent_uuid(p_agent), p_agent, 'active', true, 'meeting',
                    case when p_src = 'activity' then p_src_id end, case when p_src = 'attendee' then p_src_id end, i)
            on conflict do nothing;
        else
            update public.journey_touchpoints t
               set title = v_title, touchpoint_type = v_type,
                   due_date = case when v_due is not null and v_due is distinct from v_old_due then v_due else t.due_date end,
                   updated_at = now()
             where t.id = v_tp.id
               and (t.title is distinct from v_title or t.touchpoint_type is distinct from v_type
                    or (v_due is not null and v_due is distinct from v_old_due and t.due_date is distinct from v_due));
        end if;
    end loop;
    if p_src = 'activity' then
        delete from public.journey_touchpoints
         where source_activity_id = p_src_id and (source_seq > v_n or source_seq = 0)
           and status in ('pending', 'overdue', 'snoozed');
    else
        delete from public.journey_touchpoints
         where source_attendee_id = p_src_id and (source_seq > v_n or source_seq = 0)
           and status in ('pending', 'overdue', 'snoozed');
    end if;
    perform public.class_wait_sync_rows(p_src, p_src_id, p_pid, p_cid, p_rows, p_agent);
end $$;

-- ── Event screen: who is waiting for this session's class ───────────────────
-- Names only for people the viewer may see; others count under their agent.
create or replace function public.class_waitlist_for_session(p_activity bigint)
returns table (entry_id bigint, person_kind text, person_id bigint, person_name text, category text,
               recommended_by bigint, recommended_by_name text, since date, can_invite boolean)
language sql stable security definer set search_path = public as $$
    select w.id,
           case when w.prospect_id is not null then 'prospect' else 'customer' end,
           case when vis then coalesce(w.prospect_id, w.customer_id) end,
           case when vis then coalesce(p.full_name, c.full_name) end,
           w.category, w.recommended_by, u.full_name, w.created_at::date, vis
      from public.class_wait_entries_for(p_activity) w
      left join public.prospects p on p.id = w.prospect_id
      left join public.customers c on c.id = w.customer_id
      left join public.users u on u.id = w.recommended_by
      cross join lateral (select (coalesce(public.current_user_level(), 99) <= 2
                                  or w.recommended_by = public.current_user_row_id()
                                  or public.prospect_is_visible(w.prospect_id)
                                  or public.customer_is_visible(w.customer_id)) as vis) v
     order by w.created_at
$$;
revoke execute on function public.class_waitlist_for_session(bigint) from public, anon;
grant execute on function public.class_waitlist_for_session(bigint) to authenticated;

-- Invite from the event screen: registers the person (the attendee trigger
-- then marks them invited and closes the task).
create or replace function public.class_wait_invite(p_entry bigint, p_activity bigint) returns boolean
language plpgsql security definer set search_path = public as $$
declare e public.class_waitlist%rowtype; a record; v_me bigint := public.current_user_row_id(); v_kind text; v_pid bigint; v_name text;
begin
    select * into e from public.class_waitlist where id = p_entry and status = 'waiting';
    if e.id is null then return false; end if;
    if not (coalesce(public.current_user_level(), 99) <= 2 or e.recommended_by = v_me
            or public.prospect_is_visible(e.prospect_id) or public.customer_is_visible(e.customer_id)) then
        raise exception 'Not permitted' using errcode = '42501';
    end if;
    select id, event_id into a from public.activities where id = p_activity and activity_type = 'EVENT';
    if a.id is null then return false; end if;
    v_kind := case when e.prospect_id is not null then 'prospect' else 'customer' end;
    v_pid := coalesce(e.prospect_id, e.customer_id);
    select coalesce((select full_name from public.prospects where id = e.prospect_id), (select full_name from public.customers where id = e.customer_id)) into v_name;
    if not exists (select 1 from public.event_attendees where activity_id = a.id and attendee_type = v_kind and entity_id = v_pid) then
        insert into public.event_attendees (id, event_id, activity_id, attendee_id, entity_id, entity_name, attendee_type,
                                            attendance_status, added_by_agent_id, added_by_name, created_at)
        values ((extract(epoch from clock_timestamp()) * 1000000)::bigint, a.event_id, a.id, v_pid, v_pid, coalesce(v_name, ''), v_kind,
                'Registered', v_me, coalesce((select full_name from public.users where id = v_me), ''), now());
    end if;
    return true;
end $$;
revoke execute on function public.class_wait_invite(bigint, bigint) from public, anon;
grant execute on function public.class_wait_invite(bigint, bigint) to authenticated;

-- ── 6-month expiry, nightly ─────────────────────────────────────────────────
create or replace function public.class_wait_expire() returns integer
language plpgsql security definer set search_path = public as $$
declare v_n int;
begin
    update public.class_waitlist set status = 'expired', updated_at = now()
     where status = 'waiting' and created_at < now() - interval '6 months';
    get diagnostics v_n = row_count;
    update public.journey_touchpoints t set status = 'skipped', updated_at = now()
     where t.status in ('pending', 'overdue', 'snoozed')
       and t.source_interest_id in (select id from public.class_waitlist where status = 'expired');
    return v_n;
end $$;
revoke execute on function public.class_wait_expire() from public, anon, authenticated;
