-- ── 4. Helpers ──────────────────────────────────────────────────────────────
-- The people a list may draw from: own people, or the owner's whole downline
-- (everyone for L1–L2).
create or replace function public.nl_team_ids(p_owner bigint) returns setof bigint
language sql stable security definer set search_path = public as $$
    select u.id from public.users u
     where (select coalesce(o.role_level, 99) from public.users o where o.id = p_owner) <= 2
    union
    select t from public.pipeline_tree_ids(p_owner, true) t
     where (select coalesce(o.role_level, 99) from public.users o where o.id = p_owner) between 3 and 10
    union
    select p_owner
$$;

-- 'do_not_invite' / 'unable_to_serve' / null — the hard gate.
create or replace function public.nl_person_blocked(p_key text) returns text
language sql stable security definer set search_path = public as $$
    select case
        when left(p_key, 2) = 'c:' then (
            select case when coalesce(cu.do_not_invite, false) or coalesce(pr.do_not_invite, false) then 'do_not_invite'
                        when coalesce(pr.unable_to_serve, false) then 'unable_to_serve' end
              from public.customers cu left join public.prospects pr on pr.id = cu.converted_from_prospect_id
             where cu.id = substr(p_key, 3)::bigint)
        when left(p_key, 2) = 'p:' then (
            select case when coalesce(pr.do_not_invite, false) then 'do_not_invite'
                        when coalesce(pr.unable_to_serve, false) then 'unable_to_serve' end
              from public.prospects pr where pr.id = substr(p_key, 3)::bigint)
    end
$$;

-- Can see a list: L1–L2, the owner, the owner's uplines, or an agent with
-- people on it (once the list has started).
create or replace function public.nl_can_see(p_list bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select coalesce(public.current_user_level(), 99) <= 2
        or exists (select 1 from public.name_lists l where l.id = p_list
                     and (l.owner_id = public.current_user_row_id() or l.owner_id in (select public.current_user_visible_ids())))
        or exists (select 1 from public.name_lists l join public.name_list_rows r on r.list_id = l.id
                    where l.id = p_list and l.status <> 'draft' and r.decision <> 'removed'
                      and r.agent_id in (select public.current_user_visible_ids()))
$$;
-- Can change the list itself (rename, start, regenerate): L1–L2, owner, owner's uplines.
create or replace function public.nl_can_manage(p_list bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select coalesce(public.current_user_level(), 99) <= 2
        or exists (select 1 from public.name_lists l where l.id = p_list
                     and (l.owner_id = public.current_user_row_id() or l.owner_id in (select public.current_user_visible_ids())))
$$;
-- Can work a row (tick, contact, reply): list managers + the row's agent and their uplines.
create or replace function public.nl_can_act(p_row bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select exists (select 1 from public.name_list_rows r where r.id = p_row
                     and (public.nl_can_manage(r.list_id) or r.agent_id in (select public.current_user_visible_ids())))
$$;

-- A team list needs a team: L1–L2, or L3–L10 with someone reporting to them.
create or replace function public.nl_has_team() returns boolean
language sql stable security definer set search_path = public as $$
    select coalesce(public.current_user_level(), 99) <= 2
        or (coalesce(public.current_user_level(), 99) <= 10
            and exists (select 1 from public.users u where u.reporting_to = public.current_user_row_id()
                          and coalesce(u.status, 'active') = 'active'))
$$;

create or replace function public.nl_latest_version(p_list bigint) returns bigint
language sql stable security definer set search_path = public as $$
    select v.id from public.name_list_versions v where v.list_id = p_list order by v.version_no desc limit 1
$$;

-- Next step for one person — the first matching rule in name_list.next_step.
create or replace function public.nl_next_step(p_pid bigint, p_cid bigint, p_line_label text, p_cfg jsonb)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
    r jsonb; v_today date := public.journey_today(); v_days int; v_what text; v_d date; v_hit boolean;
    v_keys text[] := array_remove(array[case when p_cid is not null then 'c:' || p_cid end,
                                        case when p_pid is not null then 'p:' || p_pid end], null);
begin
    for r in select * from jsonb_array_elements(coalesce(p_cfg -> 'next_step', '[]'::jsonb)) loop
        continue when not coalesce((r ->> 'on')::boolean, true);
        v_days := coalesce((r ->> 'days')::int, 90); v_what := null; v_d := null; v_hit := false;
        case r ->> 'key'
            when 'task_due' then
                select coalesce(nullif(btrim(t.title), ''), nullif(btrim(t.stage_name), ''), 'follow-up'), t.due_date into v_what, v_d
                  from public.journey_touchpoints t
                 where ((p_pid is not null and t.prospect_id = p_pid) or (p_cid is not null and t.customer_id = p_cid))
                   and t.status in ('pending', 'overdue') and t.due_date <= v_today
                 order by t.due_date limit 1;
                v_hit := v_d is not null;
            when 'said_no' then
                select max(z.d) into v_d from (
                    select i.replied_at::date d from public.event_invites i
                     where i.person_key = any (v_keys) and i.reply = 'declined' and i.replied_at >= now() - make_interval(days => v_days)
                    union all
                    select s.at::date from public.name_list_steps s
                     where s.person_key = any (v_keys) and s.step in ('not_now', 'not_interested', 'stop')
                       and s.at >= now() - make_interval(days => v_days)) z;
                v_hit := v_d is not null;
            when 'open_quote' then
                select x.what, x.d into v_what, v_d from (
                    select 'audit prescription (' || left(coalesce(rx.product, ''), 30) || ')' what, rx.created_at::date d
                      from public.audit_prescriptions rx
                     where p_pid is not null and rx.prospect_id = p_pid and rx.status in ('proposed', 'accepted')
                    union all
                    select 'deal (' || left(coalesce(dl.product, ''), 30) || ')', coalesce(dl.updated_at, dl.created_at)::date
                      from public.pipeline_deals dl
                     where p_pid is not null and dl.prospect_id = p_pid and dl.stage in ('interested', 'proposal', 'prescribed', 'closing')
                    union all
                    select 'quote', a.activity_date from public.activities a
                     where ((p_pid is not null and a.prospect_id = p_pid) or (p_cid is not null and a.customer_id = p_cid))
                       and a.activity_date between v_today - v_days and v_today
                       and coalesce(a.quoted_prices::text, '') not in ('', '{}', '[]', 'null')) x
                 order by x.d desc nulls last limit 1;
                v_hit := v_what is not null;
            when 'came_no_buy' then
                select coalesce(nullif(btrim(e.title), ''), s.activity_title, 'the event'), s.activity_date into v_what, v_d
                  from public.event_attendees ea
                  join public.activities s on s.id = ea.activity_id
                  left join public.events e on e.id = s.event_id
                 where ((ea.attendee_type = 'customer' and p_cid is not null and coalesce(ea.entity_id, ea.attendee_id) = p_cid)
                     or (ea.attendee_type = 'prospect' and p_pid is not null and coalesce(ea.entity_id, ea.attendee_id) = p_pid))
                   and (coalesce(ea.attended, false) or ea.attendance_status in ('Attended', 'Late'))
                   and s.activity_date between v_today - v_days and v_today
                 order by s.activity_date desc limit 1;
                v_hit := v_d is not null and not exists (
                    select 1 from public.purchases pu
                     where ((p_cid is not null and pu.customer_id = p_cid) or (p_pid is not null and pu.prospect_id = p_pid))
                       and coalesce(pu.date, pu.created_at::date) >= v_d and coalesce(pu.status, '') !~* 'cancel|refund|void');
            when 'dormant_customer' then
                if p_cid is not null then
                    select max(coalesce(pu.date, pu.created_at::date)) into v_d from public.purchases pu
                     where (pu.customer_id = p_cid or (p_pid is not null and pu.prospect_id = p_pid))
                       and coalesce(pu.status, '') !~* 'cancel|refund|void';
                    v_hit := v_d is not null and v_d < v_today - v_days and not exists (
                        select 1 from public.activities a
                         where (a.customer_id = p_cid or (p_pid is not null and a.prospect_id = p_pid))
                           and a.activity_type in ('CPS', 'FTF', 'FSA', 'SITE', 'GR', 'XG', 'CALL', 'WHATSAPP')
                           and a.activity_date between v_today - v_days and v_today);
                end if;
            when 'default' then v_hit := true;
            else v_hit := false;
        end case;
        if v_hit then
            return jsonb_build_object('rule', r ->> 'key', 'why', r ->> 'why', 'd', v_d,
                't', replace(replace(replace(coalesce(r ->> 'text', ''),
                        '{what}', coalesce(left(v_what, 60), '')),
                        '{date}', coalesce(to_char(v_d, 'FMDD Mon'), '')),
                        '{line}', coalesce(p_line_label, '')));
        end if;
    end loop;
    return jsonb_build_object('rule', 'default', 't', 'Standard outreach', 'why', null);
end $$;

-- ── 5. Generate a version ───────────────────────────────────────────────────
-- Locks the list (two people pressing Generate cannot both make V2), runs the
-- engine, writes V(n+1). People ticked or removed in the previous version keep
-- that decision (removed stays removed, ticked stays ticked unless they are now
-- Do not contact); the engine tops each list (or each agent, for a team list)
-- up to the target. Earlier versions are never touched.
create or replace function public.nl_generate(p_list bigint, p_by bigint)
returns int language plpgsql security definer set search_path = public as $$
declare
    l public.name_lists; c jsonb := public.inv_cfg(); n jsonb := public.nl_cfg();
    v_mult numeric; v_offer int; v_line_label text; v_objs jsonb; v_no int; v_prev bigint; v_ver bigint;
    v_held jsonb; v_cand int; v_offered int; v_picked int;
begin
    select * into l from public.name_lists where id = p_list for update;
    if l.id is null then raise exception 'List not found'; end if;
    v_mult := greatest(coalesce((n ->> 'offer_multiplier')::numeric, 2.5), 1);
    v_offer := ceil(l.target_qty * v_mult)::int;
    select coalesce(label, key) into v_line_label from public.invite_lines where key = l.line;
    v_objs := jsonb_build_array(jsonb_build_object('line', l.line, 'goal', l.goal, 'focus', coalesce(l.focus, '[]'::jsonb)));
    select coalesce(max(version_no), 0) + 1 into v_no from public.name_list_versions where list_id = p_list;
    v_prev := public.nl_latest_version(p_list);

    drop table if exists _nl_scope, _nl_c, _nl_prev;
    create temp table _nl_scope on commit drop as
    select distinct t id from public.nl_team_ids(l.owner_id) t where l.scope = 'team'
    union select l.owner_id where l.scope = 'mine';

    -- engine (people outside the list's scope are not looked at)
    create temp table _nl_c on commit drop as
    select x.*, (x.excl is not null and x.excl <> 'limit') held
      from public.inv_compute(v_objs, null, null) x
     where x.agent_id in (select id from _nl_scope);

    create temp table _nl_prev on commit drop as
    select r.* from public.name_list_rows r
     where v_prev is not null and r.version_id = v_prev
       and (r.decision in ('selected', 'removed') or r.source = 'manual')
       and public.nl_person_blocked(r.person_key) is null
       and not exists (select 1 from _nl_c x where x.person_key = r.person_key and x.held);

    insert into public.name_list_versions (list_id, version_no, rules, engine_version, generated_by)
    values (p_list, v_no, jsonb_build_object(
                'engine', 'inv_compute', 'objectives', v_objs, 'invite_rules', c, 'name_list_rules', n,
                'scope', l.scope, 'scope_agents', (select coalesce(jsonb_agg(id order by id), '[]'::jsonb) from _nl_scope),
                'target_qty', l.target_qty, 'offered', v_offer,
                'order', 'Strong first, then Fit, Engaged, person key (same as Smart lists)'),
            'nl-1.0', p_by)
    returning id into v_ver;

    perform set_config('nl.engine', 'on', true);
    -- the engine's ranked people (top target × multiplier per partition) + anyone carried over
    insert into public.name_list_rows (version_id, list_id, person_key, prospect_id, customer_id, name_snapshot, agent_id,
           agent_name_snapshot, fit, engagement, readiness, grp, rank, reasons, warnings, last_touch, source,
           added_by, add_note, decision, decision_reason, decision_note, decided_by, decided_at)
    select v_ver, p_list, q.person_key, q.prospect_id, q.customer_id, coalesce(nullif(btrim(q.name), ''), '—'), q.agent_id, u.full_name,
           q.fit, q.engagement, q.readiness, q.grp, q.rk, coalesce(q.reasons, '[]'::jsonb),
           coalesce(q.warnings, '[]'::jsonb)
             || case when q.excl = 'limit' then '["invited_often"]'::jsonb else '[]'::jsonb end
             || case when q.review is not null then jsonb_build_array('check_first:' || q.review) else '[]'::jsonb end,
           q.last_touch, case when p.source = 'manual' then 'manual' else 'engine' end,
           p.added_by, p.add_note, coalesce(p.decision, 'pending'), p.decision_reason, p.decision_note, p.decided_by, p.decided_at
      from (select x.*, row_number() over (partition by case when l.scope = 'team' then x.agent_id end
                                           order by (x.grp = 'strong') desc, x.fit desc, x.engagement desc, x.person_key)::int rk
              from _nl_c x where not x.held) q
      left join _nl_prev p on p.person_key = q.person_key
      left join public.users u on u.id = q.agent_id
     where q.rk <= v_offer or p.person_key is not null;

    -- carried over but the engine no longer matches them (kept, marked)
    insert into public.name_list_rows (version_id, list_id, person_key, prospect_id, customer_id, name_snapshot, agent_id,
           agent_name_snapshot, reasons, warnings, last_touch, source, added_by, add_note,
           decision, decision_reason, decision_note, decided_by, decided_at)
    select v_ver, p_list, p.person_key, p.prospect_id, p.customer_id, p.name_snapshot, p.agent_id, p.agent_name_snapshot,
           p.reasons, '["not_matched_now"]'::jsonb, p.last_touch, case when p.source = 'manual' then 'manual' else 'carried' end,
           p.added_by, p.add_note, p.decision, p.decision_reason, p.decision_note, p.decided_by, p.decided_at
      from _nl_prev p
     where not exists (select 1 from public.name_list_rows r where r.version_id = v_ver and r.person_key = p.person_key);

    -- the engine ticks the best ones up to the target (per agent for a team list);
    -- "check first" people are offered, never ticked by the engine
    with sel as (
        select case when l.scope = 'team' then r.agent_id end part, count(*) n from public.name_list_rows r
         where r.version_id = v_ver and r.decision = 'selected' group by 1
    ), cand as (
        select r.id, case when l.scope = 'team' then r.agent_id end part,
               row_number() over (partition by case when l.scope = 'team' then r.agent_id end order by r.rank) k
          from public.name_list_rows r
         where r.version_id = v_ver and r.decision = 'pending' and r.source = 'engine'
           and not exists (select 1 from jsonb_array_elements_text(r.warnings) w where w like 'check_first:%')
    )
    update public.name_list_rows r set engine_picked = true, decision = 'selected'
      from cand c left join sel s on s.part is not distinct from c.part
     where r.id = c.id and c.k <= l.target_qty - coalesce(s.n, 0);

    -- next step per person (frozen with the version)
    update public.name_list_rows r
       set next_step = ns ->> 't', next_step_why = ns ->> 'why', next_step_rule = ns ->> 'rule'
      from (select r2.id, public.nl_next_step(r2.prospect_id,
                       coalesce(r2.customer_id, (select min(cu.id) from public.customers cu
                                                  where r2.prospect_id is not null and cu.converted_from_prospect_id = r2.prospect_id)),
                       v_line_label, n) ns
              from public.name_list_rows r2 where r2.version_id = v_ver) z
     where r.id = z.id;
    perform set_config('nl.engine', 'off', true);

    select count(*) into v_cand from _nl_c;
    select coalesce(jsonb_object_agg(excl, k), '{}'::jsonb) into v_held
      from (select excl, count(*) k from _nl_c where held group by excl) h;
    select count(*), count(*) filter (where decision = 'selected') into v_offered, v_picked
      from public.name_list_rows where version_id = v_ver;
    update public.name_list_versions set candidates = v_cand, offered = v_offered, picked = v_picked, held = v_held
     where id = v_ver;
    update public.name_lists set updated_at = now() where id = p_list;
    return v_no;
end $$;

-- ── 6. Sales → lists (one sale, one list) ───────────────────────────────────
-- A sale counts for a list when the person is ticked on its latest version and
-- the sale falls between the start and target date (or start + 90 days) + the
-- grace window. If several lists qualify, the one with the latest contact
-- before the sale wins (then the newest list). Cancelled / refunded sales drop out.
create or replace function public.nl_claim_sales() returns void
language plpgsql security definer set search_path = public as $$
declare v_win int := coalesce((public.nl_cfg() ->> 'sale_window_days')::int, 30);
begin
    delete from public.name_list_sales s
     where not exists (select 1 from public.purchases pu where pu.id = s.purchase_id
                         and coalesce(pu.status, '') !~* 'cancel|refund|void'
                         and not exists (select 1 from public.sale_cancellations sc where sc.purchase_id = pu.id
                                           and sc.status in ('refunding', 'completed')));
    insert into public.name_list_sales (purchase_id, list_id, person_key, amount, sale_date, item)
    select distinct on (pu.id) pu.id, r.list_id, r.person_key, pu.amount, coalesce(pu.date, pu.created_at::date), pu.item
      from public.purchases pu
      join lateral (select distinct k from unnest(array[
                        case when pu.customer_id is not null then 'c:' || pu.customer_id end,
                        case when pu.prospect_id is not null then 'p:' || pu.prospect_id end,
                        case when pu.prospect_id is not null then public.inv_person_key('prospect', pu.prospect_id) end,
                        (select 'p:' || cu.converted_from_prospect_id from public.customers cu
                          where cu.id = pu.customer_id and cu.converted_from_prospect_id is not null)]) k
                     where k is not null) pk on true
      join public.name_list_rows r on r.person_key = pk.k and r.decision = 'selected'
      join public.name_lists l on l.id = r.list_id and l.status in ('active', 'completed')
       and r.version_id = public.nl_latest_version(l.id)
       and coalesce(pu.date, pu.created_at::date)
           between coalesce(l.started_at, l.created_at)::date
               and coalesce(l.target_date, coalesce(l.started_at, l.created_at)::date + 90) + v_win
      left join lateral (select max(s.at) at from public.name_list_steps s
                          where s.list_id = r.list_id and s.person_key = r.person_key
                            and s.step in ('whatsapp', 'called', 'met')
                            and s.at::date <= coalesce(pu.date, pu.created_at::date)) st on true
     where coalesce(pu.date, pu.created_at::date) >= public.journey_today() - 400
       and coalesce(pu.status, '') !~* 'cancel|refund|void'
       and not exists (select 1 from public.sale_cancellations sc where sc.purchase_id = pu.id and sc.status in ('refunding', 'completed'))
       and not exists (select 1 from public.name_list_sales s where s.purchase_id = pu.id)
     order by pu.id, st.at desc nulls last, l.created_at desc, l.id desc
    on conflict (purchase_id) do nothing;
end $$;

-- ── 7. Live progress per row (contact, reply, met, sale, how often contacted) ─
-- Contact = a step on this list (WhatsApp / Called / Met) OR any call, WhatsApp
-- or meeting the agent logged on that person since the list started.
create or replace function public.nl_live(p_list bigint, p_ver bigint)
returns table (row_id bigint, contact_at timestamptz, contact_via text, contact_auto boolean,
               reply text, reply_at timestamptz, reply_note text, met_at date, met_via text,
               sale_id bigint, sale_amount numeric, sale_date date, sale_item text,
               freq int, dni boolean, phone text, prefers_call boolean)
language sql stable security definer set search_path = public as $$
    with l as (select coalesce(started_at, created_at)::date d0 from public.name_lists where id = p_list),
    cfg as (select coalesce((public.nl_cfg() ->> 'freq_days')::int, 30) fd),
    rr as (
        select r.id, r.person_key, r.prospect_id,
               coalesce(r.customer_id, (select min(cu.id) from public.customers cu
                                         where r.prospect_id is not null and cu.converted_from_prospect_id = r.prospect_id)) cid
          from public.name_list_rows r where r.version_id = p_ver
    )
    select r.id,
           case when ac.d is not null and (sc.at is null or ac.d > sc.at::date) then ac.d::timestamptz else sc.at end,
           case when ac.d is not null and (sc.at is null or ac.d > sc.at::date) then ac.t else sc.step end,
           ac.d is not null and (sc.at is null or ac.d > sc.at::date),
           sr.step, sr.at, sr.note,
           greatest(mt.d, ms.at::date),
           case when ms.at is not null and (mt.d is null or ms.at::date >= mt.d) then 'met' else mt.t end,
           sa.purchase_id, sa.amount, sa.sale_date, sa.item,
           ((select count(*) from public.name_list_steps s, cfg
              where s.person_key = r.person_key and s.step in ('whatsapp', 'called') and s.at >= now() - make_interval(days => cfg.fd))
          + (select count(*) from public.event_invites i, cfg
              where i.person_key = r.person_key and i.sent_at >= now() - make_interval(days => cfg.fd)))::int,
           coalesce(cu.do_not_invite, false) or coalesce(pr.do_not_invite, false),
           coalesce(nullif(btrim(cu.phone), ''), nullif(btrim(pr.phone), '')),
           coalesce(cu.prefers_call, false) or coalesce(pr.prefers_call, false)
      from rr r
      cross join l
      left join public.customers cu on cu.id = r.cid
      left join public.prospects pr on pr.id = r.prospect_id
      left join lateral (select case when s.step = 'clear_contact' then null else s.at end at,
                                case when s.step = 'clear_contact' then null else s.step end step
                           from public.name_list_steps s
                          where s.list_id = p_list and s.person_key = r.person_key
                            and s.step in ('whatsapp', 'called', 'met', 'clear_contact')
                          order by s.at desc, s.id desc limit 1) sc on true
      left join lateral (select a.activity_date d, a.activity_type t from public.activities a
                          where ((r.prospect_id is not null and a.prospect_id = r.prospect_id) or (r.cid is not null and a.customer_id = r.cid))
                            and a.activity_type in ('CALL', 'WHATSAPP', 'FTF', 'CPS', 'FSA', 'SITE', 'GR', 'XG')
                            and a.activity_date between l.d0 and public.journey_today()
                          order by a.activity_date desc, a.id desc limit 1) ac on true
      left join lateral (select case when s.step = 'clear_reply' then null else s.step end step,
                                case when s.step = 'clear_reply' then null else s.at end at,
                                case when s.step = 'clear_reply' then null else s.note end note
                           from public.name_list_steps s
                          where s.list_id = p_list and s.person_key = r.person_key
                            and s.step in ('interested', 'not_now', 'not_interested', 'no_reply', 'stop', 'clear_reply')
                          order by s.at desc, s.id desc limit 1) sr on true
      left join lateral (select z.d, z.t from (
                              select a.activity_date d, a.activity_type t from public.activities a
                               where ((r.prospect_id is not null and a.prospect_id = r.prospect_id) or (r.cid is not null and a.customer_id = r.cid))
                                 and a.activity_type in ('FTF', 'CPS', 'FSA', 'SITE', 'GR', 'XG')
                                 and a.activity_date between l.d0 and public.journey_today()
                              union all
                              select s.activity_date, 'EVENT' from public.event_attendees ea join public.activities s on s.id = ea.activity_id
                               where ((ea.attendee_type = 'customer' and r.cid is not null and coalesce(ea.entity_id, ea.attendee_id) = r.cid)
                                   or (ea.attendee_type = 'prospect' and r.prospect_id is not null and coalesce(ea.entity_id, ea.attendee_id) = r.prospect_id))
                                 and (coalesce(ea.attended, false) or ea.attendance_status in ('Attended', 'Late'))
                                 and s.activity_date between l.d0 and public.journey_today()) z
                          order by z.d desc limit 1) mt on true
      left join lateral (select max(s.at) at from public.name_list_steps s
                          where s.list_id = p_list and s.person_key = r.person_key and s.step = 'met') ms on true
      left join public.name_list_sales sa on sa.list_id = p_list and sa.person_key = r.person_key
$$;

-- Funnel counts for one version (viewer-scoped unless p_all).
create or replace function public.nl_counts(p_list bigint, p_ver bigint, p_all boolean)
returns jsonb language sql stable security definer set search_path = public as $$
    select jsonb_build_object(
        'picked', count(*) filter (where r.decision = 'selected'),
        'suggested', count(*) filter (where r.decision = 'pending'),
        'removed', count(*) filter (where r.decision = 'removed'),
        'contacted', count(*) filter (where r.decision = 'selected' and x.contact_at is not null),
        'replied', count(*) filter (where r.decision = 'selected' and x.reply is not null and x.reply <> 'no_reply'),
        'interested', count(*) filter (where r.decision = 'selected' and x.reply = 'interested'),
        'met', count(*) filter (where r.decision = 'selected' and x.met_at is not null),
        'closed', count(*) filter (where r.decision = 'selected' and x.sale_id is not null),
        'closed_after_contact', count(*) filter (where r.decision = 'selected' and x.sale_id is not null
                                                   and x.contact_at is not null and x.contact_at::date <= x.sale_date),
        'revenue', coalesce(sum(x.sale_amount) filter (where r.decision = 'selected'), 0),
        'agents', count(distinct r.agent_id) filter (where r.decision = 'selected'))
      from public.name_list_rows r join public.nl_live(p_list, p_ver) x on x.row_id = r.id
     where r.version_id = p_ver and (p_all or r.agent_id in (select public.current_user_visible_ids()))
$$;

