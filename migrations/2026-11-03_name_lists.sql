-- Name List → saved target lists (2026-11-03, owner).
--
-- A list = "who should I (or my team) approach for <product line × goal>, how
-- many, by when". The names come from the SAME engine as ✨ Who to invite
-- (inv_compute: Fit / Engaged / Ready + plain-word reasons) — only not tied to
-- an event session. Event invitations keep using event_invites.
--
--   name_lists          the list (purpose, line × goal, target, date, status)
--   name_list_versions  one row per Generate — a frozen copy of every rule used
--   name_list_rows      engine output per version × person (read-only after the
--                       Generate, except the decision columns: tick / remove)
--   name_list_steps     append-only log: contact, reply, decisions, adds
--   name_list_sales     a sale counts for ONE list only (purchase_id is the key)
--
-- "Do not contact" = the existing do_not_invite switch (one switch for event
-- invites AND lists, owner 2026-11-03). It is checked when a list is generated,
-- when a person is added by hand and before a contact is recorded — no level
-- can override it. Who flipped it, and when, is stamped + written to audit_trail.
--
-- All reads/writes go through SECURITY DEFINER functions (tables have RLS on and
-- no policies). Rollback: migrations/2026-11-03_name_lists_undo.sql.

-- ── 1. Tables ───────────────────────────────────────────────────────────────
create table if not exists public.name_lists (
    id          bigint generated by default as identity primary key,
    name        text not null check (char_length(btrim(name)) between 1 and 120),
    purpose     text not null check (purpose in ('promote', 'service', 'follow_up', 'other')),
    line        text not null references public.invite_lines(key),
    goal        text not null check (goal in ('introduce', 'decide', 'upgrade', 'service', 'comeback')),
    focus       jsonb not null default '[]',                     -- up to 2 product ids
    scope       text not null default 'mine' check (scope in ('mine', 'team')),
    target_qty  smallint not null check (target_qty between 1 and 200), -- team list: per agent
    target_date date,
    status      text not null default 'draft' check (status in ('draft', 'active', 'completed', 'archived')),
    remarks     text,
    owner_id    bigint not null references public.users(id),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    started_at  timestamptz
);
create index if not exists nl_owner on public.name_lists (owner_id, created_at desc);

create table if not exists public.name_list_versions (
    id             bigint generated by default as identity primary key,
    list_id        bigint not null references public.name_lists(id) on delete cascade,
    version_no     int not null,
    rules          jsonb not null,          -- frozen: objectives, scoring rules, next-step rules, scope
    engine_version text not null,
    candidates     int not null default 0,  -- matched the purpose (before hold-backs)
    offered        int not null default 0,  -- rows written
    picked         int not null default 0,  -- ticked by the engine (or carried over)
    held           jsonb not null default '{}',
    generated_at   timestamptz not null default now(),
    generated_by   bigint references public.users(id),
    constraint name_list_versions_one unique (list_id, version_no)
);

create table if not exists public.name_list_rows (
    id                  bigint generated by default as identity primary key,
    version_id          bigint not null references public.name_list_versions(id) on delete cascade,
    list_id             bigint not null references public.name_lists(id) on delete cascade,
    person_key          text not null,                -- 'c:<customer>' or 'p:<prospect>'
    prospect_id         bigint,                       -- snapshot, no FK: history survives
    customer_id         bigint,
    name_snapshot       text not null,
    agent_id            bigint,                       -- responsible agent when generated
    agent_name_snapshot text,
    fit smallint, engagement smallint, readiness smallint,
    grp                 text,
    rank                int,
    reasons             jsonb not null default '[]',
    warnings            jsonb not null default '[]',
    last_touch          date,
    engine_picked       boolean not null default false,
    next_step           text, next_step_why text, next_step_rule text,
    source              text not null default 'engine' check (source in ('engine', 'manual', 'carried')),
    added_by            bigint, add_note text,
    -- the decision layer (tick / remove) — the only columns that change later
    decision            text not null default 'pending' check (decision in ('selected', 'removed', 'pending')),
    decision_reason     text check (decision_reason in ('not_fit', 'handled', 'wrong_person', 'no_contact', 'other')),
    decision_note       text,
    decided_by          bigint,
    decided_at          timestamptz,
    created_at          timestamptz not null default now(),
    constraint name_list_rows_one unique (version_id, person_key)
);
create index if not exists nlr_list_person on public.name_list_rows (list_id, person_key);
create index if not exists nlr_agent on public.name_list_rows (agent_id);

create table if not exists public.name_list_steps (
    id         bigint generated by default as identity primary key,
    list_id    bigint not null references public.name_lists(id) on delete cascade,
    row_id     bigint references public.name_list_rows(id) on delete set null,
