-- Engine output is read-only after a Generate (only nl_generate may set it);
-- the step log is append-only.
create or replace function public.nl_rows_guard() returns trigger
language plpgsql set search_path = public as $$
begin
    if coalesce(current_setting('nl.engine', true), '') = 'on' then return new; end if;
    if (new.version_id, new.list_id, new.person_key, new.prospect_id, new.customer_id, new.name_snapshot, new.agent_id,
        new.agent_name_snapshot, new.fit, new.engagement, new.readiness, new.grp, new.rank, new.reasons, new.warnings,
        new.last_touch, new.engine_picked, new.next_step, new.next_step_why, new.next_step_rule, new.source,
        new.added_by, new.add_note)
       is distinct from
       (old.version_id, old.list_id, old.person_key, old.prospect_id, old.customer_id, old.name_snapshot, old.agent_id,
        old.agent_name_snapshot, old.fit, old.engagement, old.readiness, old.grp, old.rank, old.reasons, old.warnings,
        old.last_touch, old.engine_picked, old.next_step, old.next_step_why, old.next_step_rule, old.source,
        old.added_by, old.add_note) then
        raise exception 'The engine''s suggestion is read-only — only the tick / remove can change';
    end if;
    return new;
end $$;
drop trigger if exists name_list_rows_guard on public.name_list_rows;
create trigger name_list_rows_guard before update on public.name_list_rows for each row execute function public.nl_rows_guard();

create or replace function public.nl_steps_guard() returns trigger
language plpgsql set search_path = public as $$
begin
    raise exception 'The contact log cannot be edited';
end $$;
drop trigger if exists name_list_steps_guard on public.name_list_steps;
create trigger name_list_steps_guard before update on public.name_list_steps for each row execute function public.nl_steps_guard();

