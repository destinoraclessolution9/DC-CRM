create or replace function public.nl_dni_stamp() returns trigger
language plpgsql security definer set search_path = public as $$
begin
    if coalesce(new.do_not_invite, false) is distinct from coalesce(old.do_not_invite, false) then
        new.do_not_invite_at := case when new.do_not_invite then now() end;
        new.do_not_invite_by := case when new.do_not_invite then public.current_user_row_id() end;
        insert into public.audit_trail (actor_auth_id, actor_user_id, actor_role_level, category, action, target_table, target_id, detail)
        values (auth.uid(), public.current_user_row_id(), public.current_user_level(), 'do_not_contact',
                case when new.do_not_invite then 'on' else 'off' end, tg_table_name, new.id::text, '{}'::jsonb);
    end if;
    return new;
end $$;
drop trigger if exists prospects_dni_stamp on public.prospects;
create trigger prospects_dni_stamp before update of do_not_invite on public.prospects
    for each row execute function public.nl_dni_stamp();
drop trigger if exists customers_dni_stamp on public.customers;
create trigger customers_dni_stamp before update of do_not_invite on public.customers
    for each row execute function public.nl_dni_stamp();

