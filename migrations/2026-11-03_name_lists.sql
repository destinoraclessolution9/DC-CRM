                                             'selected', 'removed', 'pending', 'added')),
    note       text,
    data       jsonb,
    by_id      bigint,
    at         timestamptz not null default now()
);
create index if not exists nls_list_person on public.name_list_steps (list_id, person_key, at desc);
create index if not exists nls_person on public.name_list_steps (person_key, at desc);

create table if not exists public.name_list_sales (
    purchase_id bigint primary key,
    list_id     bigint not null references public.name_lists(id) on delete cascade,
    person_key  text not null,
    amount      numeric,
    sale_date   date,
    item        text,
    claimed_at  timestamptz not null default now()
);
create index if not exists nlsale_list on public.name_list_sales (list_id, person_key);

