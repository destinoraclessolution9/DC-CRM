-- ═══════════════════════════════════════════════════════════════════════════
-- Sale cancellations + refunds (owner 2026-10-22)
--
-- A customer who wants to cancel writes a request letter (reason + bank
-- details); the office replies with an official refund letter; the customer
-- signs an acceptance and sends it back; only then is the refund processed,
-- usually split over several months (company's offer, default 6). The office
-- does not use the CRM, so the AGENT records it — kept under the same invoice
-- on the DC Closing Record.
--   · the two files kept: the request letter + the signed acceptance
--   · refund total = amount paid − admin fee (editable), N months from a start month
--   · the SALE is cancelled on the signing date (goals / Won / commission stop
--     counting it); POP charges still to come are cancelled; undelivered items
--     cancelled; undo restores all of it
--   · no proof per refund month — only the date the full refund was done
--   · not allowed once anything on the order was handed over (whole order only)
--   · reminders: acceptance not back after 14 days; refund past its expected end
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists public.sale_cancellations (
    id                   bigint generated by default as identity primary key,
    purchase_id          bigint not null references public.purchases(id) on delete cascade,
    customer_id          bigint references public.customers(id) on delete set null,
    agent_id             bigint,
    status               text not null default 'requested' check (status in ('requested', 'refunding', 'completed', 'withdrawn')),
    requested_at         date not null,
    reason               text not null,
    bank_name            text not null,
    bank_account         text not null,
    account_holder       text not null,
    request_file         text not null,
    request_file_name    text,
    signed_at            date,
    acceptance_file      text,
    acceptance_file_name text,
    amount_paid          numeric,
    admin_fee            numeric,
    refund_total         numeric,
    refund_months        integer check (refund_months is null or refund_months between 1 and 60),
    first_refund_month   date,
    refunded_at          date,
    withdrawn_at         date,
    prev_status          text,
    prev_delivery_status text,
    created_by           bigint,
    updated_by           bigint,
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now(),
    check (status not in ('refunding', 'completed') or (signed_at is not null and acceptance_file is not null and refund_total is not null and refund_months is not null and first_refund_month is not null)),
    check (status <> 'completed' or refunded_at is not null)
);
-- one open case per sale (a withdrawn one can be followed by a new request)
create unique index if not exists sale_cxl_one_open on public.sale_cancellations (purchase_id) where status <> 'withdrawn';
create index if not exists sale_cxl_agent on public.sale_cancellations (agent_id);

alter table public.sale_cancellations enable row level security;
drop policy if exists sale_cxl_sel on public.sale_cancellations;
create policy sale_cxl_sel on public.sale_cancellations for select to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or agent_id in (select public.current_user_visible_ids()) or agent_id = public.current_user_row_id()
    or public.customer_is_visible(customer_id));
grant select on public.sale_cancellations to authenticated;   -- every write goes through the functions below

-- delivery items can now be cancelled with their order
alter table public.delivery_items drop constraint if exists delivery_items_status_check;
alter table public.delivery_items add constraint delivery_items_status_check check (status in ('pending', 'delivered', 'picked_up', 'cancelled'));
alter table public.delivery_items drop constraint if exists delivery_items_handover_chk;
alter table public.delivery_items add constraint delivery_items_handover_chk
    check (status in ('pending', 'cancelled') or (handover_date is not null and (jsonb_array_length(photos) > 0 or legacy_closed)));

-- ── 1. request ──────────────────────────────────────────────────────────────
create or replace function public.cancel_request(p_purchase bigint, p_requested_at date, p_reason text,
    p_bank_name text, p_bank_account text, p_account_holder text, p_file text, p_file_name text default null)
returns bigint
language plpgsql security definer set search_path = public as $$
declare pu record; v_cust bigint; v_agent bigint; v_id bigint; v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
begin
    select * into pu from public.purchases where id = p_purchase;
    if pu.id is null then raise exception 'Sale not found'; end if;
    v_cust := coalesce(pu.customer_id, (select c.id from public.customers c where c.converted_from_prospect_id = pu.prospect_id limit 1));
    v_agent := coalesce(pu.agent_id, (select responsible_agent_id from public.customers where id = v_cust));
    if not public.pop_can_act(v_agent) then raise exception 'Not allowed for this customer'; end if;
    if coalesce(pu.status, '') ~* 'cancel|refund|void' then raise exception 'This sale is already cancelled'; end if;
    if coalesce(pu.delivery_status, '') ~* '^delivered' or exists (select 1 from public.delivery_items di where di.purchase_id = p_purchase and di.status in ('delivered', 'picked_up')) then
        raise exception 'Delivered — no refund is allowed once an item has been handed over';
    end if;
    if exists (select 1 from public.sale_cancellations x where x.purchase_id = p_purchase and x.status <> 'withdrawn') then
        raise exception 'A cancellation is already open for this sale';
    end if;
    if nullif(btrim(p_reason), '') is null then raise exception 'Enter the reason'; end if;
    if nullif(btrim(p_bank_name), '') is null or nullif(btrim(p_bank_account), '') is null or nullif(btrim(p_account_holder), '') is null then
        raise exception 'Enter the bank name, account number and account holder';
    end if;
    if nullif(btrim(p_file), '') is null then raise exception 'Attach the customer''s request letter'; end if;
    if p_requested_at is null or p_requested_at > v_today then raise exception 'Enter the request date (not in the future)'; end if;
    insert into public.sale_cancellations (purchase_id, customer_id, agent_id, requested_at, reason, bank_name, bank_account, account_holder,
                                           request_file, request_file_name, amount_paid, created_by, updated_by)
    values (p_purchase, v_cust, v_agent, p_requested_at, btrim(p_reason), btrim(p_bank_name), regexp_replace(btrim(p_bank_account), '\s+', '', 'g'),
            btrim(p_account_holder), p_file, p_file_name,
            -- POP: only the months already charged count as paid
            greatest(0, coalesce(pu.amount, 0) - coalesce((select sum(i.amount) from public.pop_installments i
                where i.purchase_id = p_purchase and i.status in ('due', 'lapsed', 'waived')), 0)),
            public.current_user_row_id(), public.current_user_row_id())
    returning id into v_id;
    return v_id;
end $$;

-- ── 2. signed acceptance → sale cancelled ───────────────────────────────────
create or replace function public.cancel_sign(p_id bigint, p_signed_at date, p_file text, p_file_name text,
    p_amount_paid numeric, p_admin_fee numeric, p_refund_total numeric, p_months integer, p_first_month date)
returns boolean
language plpgsql security definer set search_path = public as $$
declare x record; pu record; v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
begin
    select * into x from public.sale_cancellations where id = p_id;
    if x.id is null then raise exception 'Cancellation not found'; end if;
    if not public.pop_can_act(x.agent_id) then raise exception 'Not allowed for this customer'; end if;
    if x.status <> 'requested' then raise exception 'Only a requested cancellation can be signed'; end if;
    if nullif(btrim(p_file), '') is null then raise exception 'Attach the signed acceptance'; end if;
    if p_signed_at is null or p_signed_at > v_today or p_signed_at < x.requested_at then raise exception 'Enter the date signed (on/after the request, not in the future)'; end if;
    if p_refund_total is null or p_refund_total < 0 then raise exception 'Enter the refund total'; end if;
    if coalesce(p_admin_fee, 0) < 0 then raise exception 'The admin fee cannot be negative'; end if;
    if p_months is null or p_months < 1 or p_months > 60 then raise exception 'Enter the number of refund months (1–60)'; end if;
    if p_first_month is null then raise exception 'Enter the first refund month'; end if;
    select * into pu from public.purchases where id = x.purchase_id;
    update public.sale_cancellations
       set status = 'refunding', signed_at = p_signed_at, acceptance_file = p_file, acceptance_file_name = p_file_name,
           amount_paid = coalesce(p_amount_paid, amount_paid), admin_fee = coalesce(p_admin_fee, 0), refund_total = p_refund_total,
           refund_months = p_months, first_refund_month = date_trunc('month', p_first_month)::date,
           prev_status = pu.status, prev_delivery_status = pu.delivery_status,
           updated_by = public.current_user_row_id(), updated_at = now()
     where id = p_id;
    -- POP charges still to come stop (history kept); undelivered items cancelled
    update public.pop_installments set status = 'waived', note = 'sale cancelled ' || p_signed_at
     where purchase_id = x.purchase_id and status in ('due', 'lapsed');
    update public.delivery_items set status = 'cancelled', remarks = coalesce(nullif(remarks, '') || ' · ', '') || 'sale cancelled ' || p_signed_at
     where purchase_id = x.purchase_id and status = 'pending';
    update public.journey_touchpoints set status = 'skipped', notes = coalesce(notes || ' · ', '') || 'auto: sale cancelled'
     where purchase_id = x.purchase_id and status = 'pending';
    -- the sale itself — everything that counts sales already skips cancelled ones
    update public.purchases set status = 'CANCELLED', delivery_status = 'Cancelled' where id = x.purchase_id;
    return true;
end $$;

-- undo a signing recorded by mistake → back to "requested", sale restored
create or replace function public.cancel_undo_sign(p_id bigint) returns boolean
language plpgsql security definer set search_path = public as $$
declare x record; v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
begin
    select * into x from public.sale_cancellations where id = p_id;
    if x.id is null or x.status <> 'refunding' then raise exception 'Only a signed (refunding) cancellation can be undone'; end if;
    if not public.pop_can_act(x.agent_id) then raise exception 'Not allowed for this customer'; end if;
    update public.purchases set status = x.prev_status, delivery_status = coalesce(x.prev_delivery_status, 'Pending Delivery') where id = x.purchase_id;
    update public.pop_installments set status = case when due_date < v_today then 'auto' else 'due' end, note = null
     where purchase_id = x.purchase_id and status = 'waived' and note like 'sale cancelled%';
    update public.delivery_items set status = 'pending' where purchase_id = x.purchase_id and status = 'cancelled';
    update public.sale_cancellations
       set status = 'requested', signed_at = null, acceptance_file = null, acceptance_file_name = null, admin_fee = null,
           refund_total = null, refund_months = null, first_refund_month = null, prev_status = null, prev_delivery_status = null,
           updated_by = public.current_user_row_id(), updated_at = now()
     where id = p_id;
    return true;
end $$;

create or replace function public.cancel_withdraw(p_id bigint, p_date date default null) returns boolean
language plpgsql security definer set search_path = public as $$
declare x record;
begin
    select * into x from public.sale_cancellations where id = p_id;
    if x.id is null or x.status <> 'requested' then raise exception 'Only a request not yet signed can be withdrawn'; end if;
    if not public.pop_can_act(x.agent_id) then raise exception 'Not allowed for this customer'; end if;
    update public.sale_cancellations set status = 'withdrawn', withdrawn_at = coalesce(p_date, (now() at time zone 'Asia/Kuala_Lumpur')::date),
           updated_by = public.current_user_row_id(), updated_at = now() where id = p_id;
    return true;
end $$;

create or replace function public.cancel_complete(p_id bigint, p_date date) returns boolean
language plpgsql security definer set search_path = public as $$
declare x record;
begin
    select * into x from public.sale_cancellations where id = p_id;
    if x.id is null or x.status not in ('refunding', 'completed') then raise exception 'Only a refunding cancellation can be completed'; end if;
    if not public.pop_can_act(x.agent_id) then raise exception 'Not allowed for this customer'; end if;
    if p_date is null or p_date > (now() at time zone 'Asia/Kuala_Lumpur')::date or p_date < x.signed_at then
        raise exception 'Enter the date the full refund was done (after signing, not in the future)';
    end if;
    update public.sale_cancellations set status = 'completed', refunded_at = p_date,
           updated_by = public.current_user_row_id(), updated_at = now() where id = p_id;
    return true;
end $$;

-- the "completed" tick can be taken back (wrong date / not actually finished)
create or replace function public.cancel_reopen(p_id bigint) returns boolean
language plpgsql security definer set search_path = public as $$
declare x record;
begin
    select * into x from public.sale_cancellations where id = p_id;
    if x.id is null or x.status <> 'completed' then raise exception 'Only a completed refund can be reopened'; end if;
    if not public.pop_can_act(x.agent_id) then raise exception 'Not allowed for this customer'; end if;
    update public.sale_cancellations set status = 'refunding', refunded_at = null,
           updated_by = public.current_user_row_id(), updated_at = now() where id = p_id;
    return true;
end $$;

do $$ begin
    execute 'revoke all on function public.cancel_request(bigint, date, text, text, text, text, text, text) from public, anon';
    execute 'grant execute on function public.cancel_request(bigint, date, text, text, text, text, text, text) to authenticated';
    execute 'revoke all on function public.cancel_sign(bigint, date, text, text, numeric, numeric, numeric, integer, date) from public, anon';
    execute 'grant execute on function public.cancel_sign(bigint, date, text, text, numeric, numeric, numeric, integer, date) to authenticated';
    execute 'revoke all on function public.cancel_undo_sign(bigint) from public, anon';
    execute 'grant execute on function public.cancel_undo_sign(bigint) to authenticated';
    execute 'revoke all on function public.cancel_withdraw(bigint, date) from public, anon';
    execute 'grant execute on function public.cancel_withdraw(bigint, date) to authenticated';
    execute 'revoke all on function public.cancel_complete(bigint, date) from public, anon';
    execute 'grant execute on function public.cancel_complete(bigint, date) to authenticated';
    execute 'revoke all on function public.cancel_reopen(bigint) from public, anon';
    execute 'grant execute on function public.cancel_reopen(bigint) to authenticated';
end $$;

-- ── reminders (08:30 MYT) ───────────────────────────────────────────────────
create or replace function public.queue_cancellation_reminders() returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date; v_n int;
begin
    insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
    select x.agent_id, 'cancellation', 'normal',
           case when x.status = 'requested' then '❌ Cancellation — ' || coalesce(c.full_name, 'customer') || ': signed acceptance not back yet'
                else '❌ Refund to ' || coalesce(c.full_name, 'customer') || ' should be finished' end,
           case when x.status = 'requested' then 'Requested ' || to_char(x.requested_at, 'FMDD Mon') || ' · ' || (v_today - x.requested_at) || ' days ago'
                else 'Expected last refund ' || to_char((x.first_refund_month + make_interval(months => x.refund_months - 1))::date, 'FMMon YYYY')
                     || ' · tick "Fully refunded" once done' end,
           './index.html?cxl=1#customers', 'cancellation:' || x.id || ':' || v_today, now()
      from public.sale_cancellations x
      left join public.customers c on c.id = x.customer_id
     where x.agent_id is not null
       and ((x.status = 'requested' and v_today - x.requested_at >= 14 and (v_today - x.requested_at) % 7 = 0)
         or (x.status = 'refunding'
             and v_today > (date_trunc('month', x.first_refund_month + make_interval(months => x.refund_months - 1)) + interval '1 month - 1 day')::date
             and (v_today - (date_trunc('month', x.first_refund_month + make_interval(months => x.refund_months - 1)) + interval '1 month - 1 day')::date) % 7 = 1))
    on conflict (user_id, dedupe_key) do nothing;
    get diagnostics v_n = row_count;
    return v_n;
end $$;
revoke all on function public.queue_cancellation_reminders() from public, anon, authenticated;
select cron.unschedule('cancellation-reminders') where exists (select 1 from cron.job where jobname = 'cancellation-reminders');
select cron.schedule('cancellation-reminders', '35 0 * * *', 'select public.queue_cancellation_reminders();');

-- ── POP: a cancelled sale keeps its history (was: schedule deleted) ─────────
create or replace function public.pop_plan_sync(p_purchase bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare
    pu record; tm record; k int; v_due date; v_n int := 0; v_cust bigint; v_agent bigint;
    v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
begin
    select * into pu from public.purchases where id = p_purchase;
    if pu.id is null then return 0; end if;
    tm := public.pop_plan_terms(p_purchase);
    -- a cancelled sale keeps its charge history; only what was still to come stops
    if coalesce(pu.status, '') ~* 'cancel|refund|void' then
        update public.pop_installments set status = 'waived', note = coalesce(note, 'sale cancelled')
         where purchase_id = p_purchase and status in ('due', 'lapsed');
        return 0;
    end if;
    if not coalesce(tm.is_plan, false) then
        delete from public.pop_installments where purchase_id = p_purchase and status in ('due', 'auto', 'assumed') and not amount_edited;
        return 0;
    end if;
    if exists (select 1 from public.pop_installments where purchase_id = p_purchase)
       and not exists (select 1 from public.pop_installments where purchase_id = p_purchase
                        and (status in ('lapsed', 'paid_manual', 'waived') or amount_edited))
       and ((select count(*) from public.pop_installments where purchase_id = p_purchase) <> tm.tenure
            or exists (select 1 from public.pop_installments where purchase_id = p_purchase and amount <> tm.monthly)
            or exists (select 1 from public.pop_installments where purchase_id = p_purchase and seq = 1
                        and due_date <> (pu.date + interval '1 month')::date)) then
        delete from public.pop_installments where purchase_id = p_purchase;
    end if;
    v_cust := coalesce(pu.customer_id, (select c.id from public.customers c where c.converted_from_prospect_id = pu.prospect_id limit 1));
    v_agent := coalesce(pu.agent_id, (select responsible_agent_id from public.customers where id = v_cust));
    if exists (select 1 from public.pop_installments where purchase_id = p_purchase) then
        update public.pop_installments set customer_id = v_cust, agent_id = v_agent
         where purchase_id = p_purchase and (customer_id is distinct from v_cust or agent_id is distinct from v_agent);
        return 0;
    end if;
    for k in 1 .. tm.tenure loop
        v_due := (pu.date + make_interval(months => k))::date;
        insert into public.pop_installments (purchase_id, customer_id, agent_id, seq, due_date, amount, status, note)
        values (p_purchase, v_cust, v_agent, k, v_due, tm.monthly,
                case when v_due < date '2026-10-01' then 'assumed' when v_due < v_today then 'auto' else 'due' end,
                case when v_due < date '2026-10-01' then 'before tracking began' end);
        v_n := v_n + 1;
    end loop;
    return v_n;
exception when others then
    return 0;
end $$;
revoke all on function public.pop_plan_sync(bigint) from public, anon, authenticated;
