    pop_down_payment, amount, date, status, item, customer_id, agent_id on public.purchases
    for each row execute function public.pop_purchase_trg();

-- ── Scope (same rule as the Goal Bar: L1–2 company, L3–5 tree, else own) ────
create or replace function public.pop_scope_ids() returns setof bigint
language plpgsql stable security definer set search_path = public as $$
declare v_uid bigint := public.current_user_row_id(); v_lvl int := coalesce(public.current_user_level(), 99);
begin
    if v_lvl <= 2 then return query select u.id from public.users u;
    elsif v_uid is not null then return query select public.pipeline_tree_ids(v_uid, v_lvl between 3 and 5);
    end if;
end $$;
revoke all on function public.pop_scope_ids() from public, anon;
grant execute on function public.pop_scope_ids() to authenticated;

create or replace function public.pop_summary()
returns table (outstanding numeric, plans integer, due_month numeric, due_month_n integer,
               overdue numeric, overdue_n integer, failed_n integer, collected_month numeric, due_90 numeric)
language sql stable security definer set search_path = public as $$
    with t as (select (now() at time zone 'Asia/Kuala_Lumpur')::date d),
    s as (select i.* from public.pop_installments i
           where i.agent_id in (select public.pop_scope_ids())
              or (coalesce(public.current_user_level(), 99) <= 2 and i.agent_id is null))
    select coalesce(sum(s.amount) filter (where s.status in ('due', 'failed')), 0),
           count(distinct s.purchase_id) filter (where s.status in ('due', 'failed'))::int,
           coalesce(sum(s.amount) filter (where s.status in ('due', 'failed') and date_trunc('month', s.due_date) = date_trunc('month', t.d)), 0),
           count(*) filter (where s.status in ('due', 'failed') and date_trunc('month', s.due_date) = date_trunc('month', t.d))::int,
           coalesce(sum(s.amount) filter (where (s.status = 'due' and s.due_date < t.d) or s.status = 'failed'), 0),
           count(*) filter (where (s.status = 'due' and s.due_date < t.d) or s.status = 'failed')::int,
           count(*) filter (where s.status = 'failed')::int,
           coalesce(sum(s.amount) filter (where s.status = 'paid' and date_trunc('month', s.paid_date) = date_trunc('month', t.d)), 0),
           coalesce(sum(s.amount) filter (where s.status in ('due', 'failed') and s.due_date <= t.d + 90), 0)
      from t left join s on true group by t.d
$$;
revoke all on function public.pop_summary() from public, anon;
grant execute on function public.pop_summary() to authenticated;

-- The 💳 line on a profile: one row per POP plan of that person.
create or replace function public.pop_person_plans(p_pid bigint)
returns table (purchase_id bigint, item text, total integer, done integer, left_rm numeric,
               next_due date, next_amount numeric, failed integer, monthly numeric)
language plpgsql stable security definer set search_path = public as $$
declare v_cid bigint;
begin
    select c.id into v_cid from public.customers c where c.converted_from_prospect_id = p_pid order by c.id limit 1;
    if v_cid is null or not (public.customer_is_visible(v_cid) or public.prospect_is_visible(p_pid)) then return; end if;
    return query
    select i.purchase_id, max(pu.item), count(*)::int,
           (count(*) filter (where i.status in ('paid', 'assumed', 'waived')))::int,
           coalesce(sum(i.amount) filter (where i.status in ('due', 'failed')), 0),
           min(i.due_date) filter (where i.status = 'due'),
           (array_agg(i.amount order by i.due_date) filter (where i.status = 'due'))[1],
           (count(*) filter (where i.status = 'failed'))::int,
           max(i.amount)
      from public.pop_installments i join public.purchases pu on pu.id = i.purchase_id
     where i.customer_id = v_cid
     group by i.purchase_id
     order by min(i.due_date) filter (where i.status = 'due') nulls last;
end $$;
revoke all on function public.pop_person_plans(bigint) from public, anon;
grant execute on function public.pop_person_plans(bigint) to authenticated;

-- 1st of the month 08:40 MYT: what to charge this month (L1–L5, own scope)
create or replace function public.queue_pop_month_push() returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date; v_n int;
begin
    insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
    select u.id, 'pop_month', 'normal',
           '💳 POP: ' || x.n || ' charge' || case when x.n = 1 then '' else 's' end || ' due this month · RM' || round(x.rm),
           case when x.od > 0 then x.od || ' overdue / failed · ' else '' end || 'open the 💳 POP board to tick them',
           './index.html?pop=1#pipeline', 'pop_month:' || to_char(v_today, 'YYYY-MM'), now()
      from public.users u
      cross join lateral (
          select count(*) filter (where date_trunc('month', i.due_date) = date_trunc('month', v_today)) n,
                 coalesce(sum(i.amount) filter (where date_trunc('month', i.due_date) = date_trunc('month', v_today)), 0) rm,
                 count(*) filter (where i.status = 'failed' or i.due_date < v_today) od
            from public.pop_installments i
           where i.status in ('due', 'failed')
             and (u.role_level <= 2 or i.agent_id in (select public.pipeline_tree_ids(u.id, true)))) x
     where u.role_level between 1 and 5 and x.n + x.od > 0
       and coalesce(u.status, 'active') !~* 'inactive|deleted|resign|terminat'
    on conflict (user_id, dedupe_key) do nothing;
    get diagnostics v_n = row_count;
    return v_n;
end $$;
revoke all on function public.queue_pop_month_push() from public, anon, authenticated;
select cron.unschedule('pop-month-push') where exists (select 1 from cron.job where jobname = 'pop-month-push');
select cron.schedule('pop-month-push', '40 0 1 * *', 'select public.queue_pop_month_push();');

-- ── 📋 top 5: failed / overdue POP charges (redefines the autopilot function) ──
create or replace function public.journey_todo_for(p_uid bigint, p_limit integer default 5)
returns table (kind text, icon text, prospect_id bigint, customer_id bigint, name text, why text, rm numeric, due date, score numeric, ref_id bigint)
language sql stable security definer set search_path = public as $$
with t as (select public.journey_today() d),
c as (   -- ① collections: ready ≤ 7 days, not handed over
    select 'collect'::text kind, '📦'::text icon, cu.converted_from_prospect_id pid, cu.id cid, cu.full_name nm,
           case when di.expected_ready_date < t.d then 'Collect ' || left(di.item_name, 30) || ' · ready since ' || to_char(di.expected_ready_date, 'FMDD Mon')
                else 'Ready ' || to_char(di.expected_ready_date, 'FMDD Mon') || ' · book the collection + photo' end why,
           coalesce(pu.amount, 10000) rm, di.expected_ready_date due,
           greatest(coalesce(pu.amount, 10000), 3000) * case when di.expected_ready_date < t.d then 3 else 2 end
             * (1 + least(greatest(t.d - di.expected_ready_date, 0), 30) / 30.0) sc, di.purchase_id ref
      from public.delivery_items di cross join t
      join public.customers cu on cu.id = di.customer_id
      left join public.purchases pu on pu.id = di.purchase_id
     where di.status = 'pending' and di.expected_ready_date <= t.d + 7
       and di.expected_ready_date >= t.d - 120
       and coalesce(pu.agent_id, cu.responsible_agent_id) = p_uid
),
g as (   -- ② Golden Road session due
    select 'gr', '🟣', coalesce(tp.prospect_id, cu.converted_from_prospect_id), tp.customer_id, coalesce(cu.full_name, pr.full_name),
           'Golden Road ' || tp.seq || '/' || tp.seq_total || case when tp.due_date < t.d then ' · overdue' else ' · due ' || to_char(tp.due_date, 'FMDD Mon') end,
           coalesce(pu.amount, 10000), tp.due_date,
           greatest(coalesce(pu.amount, 10000), 3000) * 2 * (1 + least(greatest(t.d - tp.due_date, 0), 30) / 30.0), tp.purchase_id
      from public.journey_touchpoints tp cross join t
      left join public.customers cu on cu.id = tp.customer_id
      left join public.prospects pr on pr.id = tp.prospect_id
      left join public.purchases pu on pu.id = tp.purchase_id
     where tp.status = 'pending' and tp.seq is not null and tp.assigned_to_id = p_uid and tp.due_date <= t.d + 3
       and coalesce(tp.snooze_until, t.d) <= t.d
),
cps as ( -- ③ CPS with no 2nd meeting (A)
    select 'cps', '🆕', p.id, null::bigint, p.full_name,
           'CPS ' || to_char(x.d, 'FMDD Mon') || ' · no 2nd meeting booked',
           coalesce(nullif(p.open_potential_rm, 0), 5000), x.d,
           greatest(coalesce(p.open_potential_rm, 0), 5000) * 1.5 * case when t.d - x.d <= 14 then 1.2 else 0.8 end, null::bigint
      from public.prospects p cross join t
      cross join lateral (select max(a.activity_date) d from public.activities a where a.prospect_id = p.id and a.activity_type = 'CPS') x
     where p.responsible_agent_id = p_uid and x.d between t.d - 30 and t.d - 1
       and coalesce(p.status, '') not in ('converted', 'lost') and not coalesce(p.unable_to_serve, false)
       and coalesce(p.manual_grade, '') <> 'F' and coalesce(p.cps_next_step, '') <> 'not_interested'
       and not exists (select 1 from public.activities a where a.prospect_id = p.id and a.activity_date > x.d
                         and a.activity_type in ('CPS', 'FTF', 'FSA', 'SITE', 'GR', 'EVENT', 'EVENT_CLOSING'))
       and not exists (select 1 from public.event_attendees ea where ea.attendee_type = 'prospect' and ea.entity_id = p.id
                         and ea.created_at::date >= x.d)
),
hot as ( -- ④ Commit / Audit / Hot with nothing booked
    select 'book', case p.potential_tier when 'commit' then '🟢' when 'audit' then '🩺' else '🔥' end, p.id, null::bigint, p.full_name,
           initcap(p.potential_tier) || ' · RM' || round(p.open_potential_rm / 1000) || 'k · nothing booked'
             || coalesce(' · met ' || to_char(p.potential_last_met, 'FMDD Mon'), ''),
           p.open_potential_rm, p.potential_last_met,
           p.open_potential_rm * case p.potential_tier when 'commit' then 3 when 'audit' then 2 else 1.5 end
             * (1 + least(coalesce(t.d - p.potential_last_met, 60), 60) / 60.0), null::bigint
      from public.prospects p cross join t
     where p.responsible_agent_id = p_uid and p.potential_tier in ('commit', 'audit', 'hot')
       and p.potential_next_booked is null and p.open_potential_rm > 0
),
tp as (  -- ⑤ any other journey step due today or overdue
    select 'touch', '🧭', coalesce(j.prospect_id, cu.converted_from_prospect_id), j.customer_id, coalesce(cu.full_name, pr.full_name),
           regexp_replace(j.title, '^\S+\s+', '') || case when j.due_date < t.d then ' · overdue' else '' end,
           coalesce(nullif(pr.open_potential_rm, 0), 3000), j.due_date,
           greatest(coalesce(pr.open_potential_rm, 0), 3000) * case when j.priority = 'high' then 1.2 else 1 end
             * (1 + least(greatest(t.d - j.due_date, 0), 30) / 30.0), j.id
      from public.journey_touchpoints j cross join t
      left join public.customers cu on cu.id = j.customer_id
      left join public.prospects pr on pr.id = j.prospect_id
     where j.status = 'pending' and j.seq is null and j.assigned_to_id = p_uid and j.due_date <= t.d
       and j.due_date >= t.d - 60 and coalesce(j.snooze_until, t.d) <= t.d
),
pop as ( -- ⑥ POP card charge failed / overdue a week
    select 'pop', '💳', cu.converted_from_prospect_id, cu.id, cu.full_name,
           'POP ' || i.seq || '/' || x.n || ' ' || case when i.status = 'failed' then 'charge failed' else 'overdue since ' || to_char(i.due_date, 'FMDD Mon') end
             || ' · RM' || round(i.amount) || ' — update the card / collect',
           x.left_rm, i.due_date,
           greatest(x.left_rm, 3000) * 2.5 * (1 + least(greatest(t.d - i.due_date, 0), 60) / 60.0), i.purchase_id
      from public.pop_installments i cross join t
      join public.customers cu on cu.id = i.customer_id
      cross join lateral (select count(*) n, coalesce(sum(j.amount) filter (where j.status in ('due', 'failed')), 0) left_rm
                            from public.pop_installments j where j.purchase_id = i.purchase_id) x
     where i.agent_id = p_uid and (i.status = 'failed' or (i.status = 'due' and i.due_date < t.d - 7))
),
allx as (select * from c union all select * from g union all select * from cps union all select * from hot union all select * from tp union all select * from pop),
best as (
    select distinct on (coalesce('c' || cid::text, 'p' || pid::text)) * from allx
     where nm is not null
     order by coalesce('c' || cid::text, 'p' || pid::text), sc desc
)
select kind, icon, pid, cid, nm, why, rm, due, round(sc), ref from best order by sc desc limit greatest(coalesce(p_limit, 5), 1)
$$;
revoke all on function public.journey_todo_for(bigint, integer) from public, anon, authenticated;
revoke all on function public.journey_todo_for(bigint, integer) from public, anon, authenticated;

-- ── Backfill every existing plan ───────────────────────────────────────────
-- New sales from closing approvals now carry tenure + monthly (ui.js
-- purchasePaymentTerms); copy them onto the POP sales already booked.
update public.purchases pu
   set installment_tenure = coalesce(pu.installment_tenure, a.pop_tenure),
       pop_monthly_amount = coalesce(pu.pop_monthly_amount, a.pop_monthly_amount)
  from public.activities a
 where a.is_closing and a.payment_method = 'POP' and a.activity_date = pu.date
   and pu.payment_method ~* '\mpop\M' and coalesce(a.pop_tenure, 0) > 0
   and (a.customer_id = pu.customer_id or a.prospect_id = pu.prospect_id
        or a.prospect_id = (select c.converted_from_prospect_id from public.customers c where c.id = pu.customer_id))
   and (pu.installment_tenure is null or pu.pop_monthly_amount is null);
select count(*) filter (where public.pop_plan_sync(id) > 0) as plans_built from public.purchases;
