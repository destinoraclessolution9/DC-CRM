-- ═══════════════════════════════════════════════════════════════════════════
-- POP (company-financed instalment) collections (2026-10-20)
--
-- A POP sale = down payment + N monthly card charges the company runs itself.
-- Until now the CRM kept only the tenure (purchases.epp_months on imports,
-- installment_tenure on new sales; the monthly amount stayed on the closing
-- activity), so nobody could see what is still owed or which charge failed.
--
--   pop_installments  one row per monthly charge: due · paid · failed · waived
--                     · assumed (fell due before tracking began — nothing was
--                     ever recorded, so it is counted as collected and marked)
--   pop_plan_sync()   builds / rebuilds a sale's schedule (trigger on purchases)
--   pop_summary()     outstanding · due this month · overdue · collected, for
--                     the viewer's scope (company / team tree / own)
--   pop_person_plans  the 💳 line on a profile
--   journey_todo_for  + failed / overdue charges on the agent's 📋 top 5
--   queue_pop_month_push  1st of the month 08:40 MYT → L1–L5 "charges due"
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.purchases add column if not exists pop_monthly_amount numeric;

create table if not exists public.pop_installments (
    id          bigint generated by default as identity primary key,
    purchase_id bigint not null references public.purchases(id) on delete cascade,
    customer_id bigint references public.customers(id) on delete set null,
    agent_id    bigint,
    seq         integer not null,
    due_date    date not null,
    amount      numeric not null,
    status      text not null default 'due' check (status in ('due', 'paid', 'failed', 'waived', 'assumed')),
    paid_date   date,
    note        text,
    updated_by  bigint,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    unique (purchase_id, seq)
);
create index if not exists pop_inst_due on public.pop_installments (due_date) where status in ('due', 'failed');
create index if not exists pop_inst_cust on public.pop_installments (customer_id);

alter table public.pop_installments enable row level security;
drop policy if exists pop_inst_sel on public.pop_installments;
create policy pop_inst_sel on public.pop_installments for select to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or agent_id in (select public.current_user_visible_ids()) or agent_id = public.current_user_row_id()
    or public.customer_is_visible(customer_id));
-- ticking a charge: admins, team leaders over that agent, or the sale's agent
drop policy if exists pop_inst_upd on public.pop_installments;
create policy pop_inst_upd on public.pop_installments for update to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or agent_id in (select public.current_user_visible_ids()) or agent_id = public.current_user_row_id())
    with check (status in ('due', 'paid', 'failed', 'waived', 'assumed'));
grant select, update on public.pop_installments to authenticated;

create or replace function public.pop_inst_touch() returns trigger
language plpgsql as $$
begin
    new.updated_at := now();
    if new.status = 'paid' and new.paid_date is null then new.paid_date := (now() at time zone 'Asia/Kuala_Lumpur')::date; end if;
    if new.status <> 'paid' and old.status = 'paid' then new.paid_date := null; end if;
    new.updated_by := coalesce(public.current_user_row_id(), new.updated_by);
    return new;
end $$;
drop trigger if exists trg_pop_inst_touch on public.pop_installments;
create trigger trg_pop_inst_touch before update on public.pop_installments
    for each row execute function public.pop_inst_touch();

-- ── Terms: tenure · monthly · down payment ─────────────────────────────────
create or replace function public.pop_plan_terms(p_purchase bigint,
    out is_plan boolean, out tenure integer, out monthly numeric, out down numeric)
language plpgsql stable security definer set search_path = public as $$
declare pu record; a record; v_pid bigint;
begin
    is_plan := false;
    select * into pu from public.purchases where id = p_purchase;
    if pu.id is null or coalesce(pu.amount, 0) <= 0 or coalesce(pu.status, '') ~* 'cancel|refund|void'
       or coalesce(pu.item, '') ~* 'imported|pre-system' then return; end if;
    -- POP / pre-own (PREON) plans; a bank-run EPP is paid to us in full → not ours to collect
    if not (coalesce(pu.payment_method, '') ~* '(\mpop\M|pre.?own|preon)'
            or ((coalesce(pu.epp_months, 0) > 0 or coalesce(pu.installment_tenure, 0) > 0)
                and coalesce(pu.payment_method, '') !~* '^\s*epp\s*$')) then return; end if;
    select c.converted_from_prospect_id into v_pid from public.customers c where c.id = pu.customer_id;
    select x.pop_tenure, x.pop_monthly_amount, x.pop_down_payment into a
      from public.activities x
     where x.is_closing and x.payment_method = 'POP' and x.activity_date = pu.date
       and (x.customer_id = pu.customer_id or x.prospect_id in (pu.prospect_id, v_pid))
     order by abs(coalesce(x.closing_amount, x.amount_closed, 0) - pu.amount) limit 1;
    tenure  := coalesce(nullif(pu.installment_tenure, 0), nullif(pu.epp_months, 0), nullif(a.pop_tenure, 0));
    down    := coalesce(pu.pop_down_payment, a.pop_down_payment, 0);
    monthly := coalesce(nullif(pu.pop_monthly_amount, 0), nullif(a.pop_monthly_amount, 0),
                        case when tenure > 0 then round((pu.amount - down) / tenure, 2) end);
    -- nonsense terms (e.g. a RM399 row that is itself one month): leave it unscheduled
    is_plan := coalesce(tenure between 2 and 120 and monthly >= 50, false);
end $$;

-- ── Build / rebuild one sale's schedule ────────────────────────────────────
create or replace function public.pop_plan_sync(p_purchase bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare
    pu record; tm record; v_cut date; k int; v_due date; v_n int := 0; v_cust bigint; v_agent bigint;
begin
    select * into pu from public.purchases where id = p_purchase;
    if pu.id is null then return 0; end if;
    tm := public.pop_plan_terms(p_purchase);
    if not coalesce(tm.is_plan, false) then
        -- not (or no longer) a plan: drop what was never acted on
        delete from public.pop_installments where purchase_id = p_purchase and status in ('due', 'assumed');
        return 0;
    end if;
    -- terms changed and nothing was ticked yet → rebuild
    if exists (select 1 from public.pop_installments where purchase_id = p_purchase)
       and not exists (select 1 from public.pop_installments where purchase_id = p_purchase and status in ('paid', 'failed', 'waived'))
       and ((select count(*) from public.pop_installments where purchase_id = p_purchase) <> tm.tenure
            or exists (select 1 from public.pop_installments where purchase_id = p_purchase and amount <> tm.monthly)
            or exists (select 1 from public.pop_installments where purchase_id = p_purchase and seq = 1
                        and due_date <> (pu.date + interval '1 month')::date)) then
        delete from public.pop_installments where purchase_id = p_purchase;
    end if;
    v_cust := coalesce(pu.customer_id, (select c.id from public.customers c where c.converted_from_prospect_id = pu.prospect_id limit 1));
    v_agent := coalesce(pu.agent_id, (select responsible_agent_id from public.customers where id = v_cust));
    if exists (select 1 from public.pop_installments where purchase_id = p_purchase) then
        update public.pop_installments set customer_id = v_cust, agent_id = v_agent
         where purchase_id = p_purchase and (customer_id is distinct from v_cust or agent_id is distinct from v_agent);
        return 0;
    end if;
    -- charges due before tracking began were never recorded → "assumed" collected
    v_cut := greatest(coalesce(pu.created_at::date, current_date), date '2026-10-20');
    for k in 1 .. tm.tenure loop
        v_due := (pu.date + make_interval(months => k))::date;
        insert into public.pop_installments (purchase_id, customer_id, agent_id, seq, due_date, amount, status, note)
        values (p_purchase, v_cust, v_agent, k, v_due, tm.monthly,
                case when v_due < v_cut then 'assumed' else 'due' end,
                case when v_due < v_cut then 'before tracking began' end);
        v_n := v_n + 1;
    end loop;
    return v_n;
exception when others then
    return 0;
end $$;
revoke all on function public.pop_plan_terms(bigint) from public, anon, authenticated;
revoke all on function public.pop_plan_sync(bigint) from public, anon, authenticated;

create or replace function public.pop_purchase_trg() returns trigger
language plpgsql security definer set search_path = public as $$
begin
    perform public.pop_plan_sync(new.id);
    return null;
exception when others then
    return null;
end $$;
drop trigger if exists trg_pop_purchase on public.purchases;
