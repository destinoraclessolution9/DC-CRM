-- =============================================================================
-- delivery_items_2026-10-19.sql
-- Per-item delivery / pick-up tracking for the Product Delivery Listing.
--
-- Owner 2026-10-19: every product is custom-made (rings ~6 months), so one order
-- can hold several items that are handed over on different days — or together.
-- Each item records:
--   * expected_ready_date — the closing form's "Collection Date" (when the item
--     should be ready). Never the sale date: reports count the sale on order_date.
--   * status pending → delivered | picked_up, with handover_date + photos.
--     A handover REQUIRES a date and at least one photo (enforced below).
-- A daily job queues a phone push to the agent 30 days before an item is ready.
--
-- Scoping: staff only (level <= 12) — same audience as the delivery board.
-- Customers / referrers (L13+) never see it. Additive + idempotent.
-- =============================================================================

create table if not exists public.delivery_items (
  id                  bigint generated by default as identity primary key,
  customer_id         bigint not null,
  purchase_id         bigint,            -- purchases row (most orders)
  prospect_id         bigint,            -- legacy conversion sale with no purchases row
  item_name           text   not null check (length(btrim(item_name)) > 0),
  qty                 integer not null default 1 check (qty > 0),
  ring_size           text,
  expected_ready_date date,
  status              text   not null default 'pending'
                      check (status in ('pending', 'delivered', 'picked_up')),
  handover_date       date,
  photos              jsonb  not null default '[]'::jsonb,   -- attachments-bucket object paths
  remarks             text,
  handed_over_by      bigint,
  created_by          bigint,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint delivery_items_parent_chk check (purchase_id is not null or prospect_id is not null),
  constraint delivery_items_photos_array_chk check (jsonb_typeof(photos) = 'array'),
  -- Photo proof is mandatory: no handover without a date and >= 1 photo.
  constraint delivery_items_handover_chk check (
    status = 'pending'
    or (handover_date is not null and jsonb_array_length(photos) > 0)
  )
);

create index if not exists delivery_items_purchase_idx on public.delivery_items (purchase_id);
create index if not exists delivery_items_prospect_idx on public.delivery_items (prospect_id);
create index if not exists delivery_items_customer_idx on public.delivery_items (customer_id);
create index if not exists delivery_items_ready_idx
  on public.delivery_items (expected_ready_date) where status = 'pending';

create or replace function public.delivery_items_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists delivery_items_touch on public.delivery_items;
create trigger delivery_items_touch before update on public.delivery_items
  for each row execute function public.delivery_items_touch();

alter table public.delivery_items enable row level security;

drop policy if exists delivery_items_staff_all on public.delivery_items;
create policy delivery_items_staff_all on public.delivery_items
  for all to authenticated
  using (coalesce(public.current_user_level(), 99) <= 12)
  with check (coalesce(public.current_user_level(), 99) <= 12);

grant select, insert, update, delete on public.delivery_items to authenticated;
grant all on public.delivery_items to service_role;

-- ── 30-day "ready soon" reminder ───────────────────────────────────────────
-- One push per item per expected date (changing the date re-arms it) to the
-- credited agent (purchases.agent_id, else the customer's owner). Rows land in
-- notification_outbox; the every-minute notification-dispatch job delivers them
-- (bell fallback when the agent has no phone signed up).
create or replace function public.queue_delivery_ready_reminders()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
  v_n     integer;
begin
  insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
  select a.agent_id,
         'delivery_ready',
         'normal',
         '📦 Ready in ' || (di.expected_ready_date - v_today) || ' days',
         to_char(di.expected_ready_date, 'FMDD Mon') || ' · ' || left(di.item_name, 40)
           || coalesce(' | ' || nullif(c.full_name, ''), ''),
         './index.html?delivery=1#customers',
         'delivery_ready:' || di.id || ':' || di.expected_ready_date,
         now()
    from public.delivery_items di
    join public.customers c on c.id = di.customer_id
    left join public.purchases p on p.id = di.purchase_id
    cross join lateral (select coalesce(p.agent_id, c.responsible_agent_id) as agent_id) a
   where di.status = 'pending'
     and di.expected_ready_date between v_today and v_today + 30
     and a.agent_id is not null
  on conflict (user_id, dedupe_key) do nothing;
  get diagnostics v_n = row_count;
  return v_n;
end;
$$;
revoke all on function public.queue_delivery_ready_reminders() from public, anon, authenticated;

do $$
begin
  if exists (select 1 from cron.job where jobname = 'delivery-ready-reminders') then
    perform cron.unschedule('delivery-ready-reminders');
  end if;
  -- 01:00 UTC = 09:00 MYT daily.
  perform cron.schedule('delivery-ready-reminders', '0 1 * * *', 'select public.queue_delivery_ready_reminders();');
end;
$$;

-- ── Backfill: one item per undelivered sale ────────────────────────────────
-- Expected ready = the matching closing record's Collection Date, only when it
-- is AFTER the order date (many records repeat the order date there, which is
-- not a real ready date).
insert into public.delivery_items (customer_id, purchase_id, item_name, ring_size, expected_ready_date, status)
select p.customer_id,
       p.id,
       coalesce(nullif(btrim(p.item), ''), 'Item'),
       nullif(btrim(p.ring_size), ''),
       (select (h->>'closing_date')::date
          from public.customers c
          join public.prospects pr on pr.id = c.converted_from_prospect_id
          cross join lateral jsonb_array_elements(
            case when jsonb_typeof(pr.closing_records_history) = 'array' then pr.closing_records_history else '[]'::jsonb end
            || case when jsonb_typeof(pr.closing_record) = 'object' then jsonb_build_array(pr.closing_record) else '[]'::jsonb end
          ) h
         where c.id = p.customer_id
           and lower(btrim(coalesce(h->>'invoice_number', ''))) = lower(btrim(coalesce(p.invoice, '')))
           and btrim(coalesce(p.invoice, '')) <> ''
           and coalesce(h->>'closing_date', '') ~ '^\d{4}-\d{2}-\d{2}$'
           and (coalesce(h->>'order_date', '') !~ '^\d{4}-\d{2}-\d{2}$'
                or (h->>'closing_date')::date > (h->>'order_date')::date)
         limit 1),
       'pending'
  from public.purchases p
 where coalesce(p.delivery_status, 'Pending Delivery') <> 'Delivered'
   and coalesce(p.is_agent_package, false) = false
   and p.customer_id is not null
   and not exists (select 1 from public.delivery_items d where d.purchase_id = p.id);
