-- WHY (owner 2026-11-12): an agent's own calligraphy / artistic masterpieces /
-- 财库·财托 were only known to the CRM once lent to a customer (delivery_advances).
-- Pieces still in the agent's hands had nowhere to go.
--
-- WHAT
--  * agent_stock_moves — append-only ledger per agent: added / adjust by hand;
--    lent / returned / unlent written by a trigger on delivery_advances, so a
--    handover "from agent's own stock" takes the piece out of the agent's hands and
--    "↩ Returned to me" puts the office piece back. In hand = sum(qty).
--  * Stock is counted per product (promo / launch-price variants count as the
--    plain product: same physical piece).
--  * agent_stock_balance() / agent_stock_counts() run as the caller (RLS: the
--    agent, their upline, admin).
--  * delivery_advance_allowed() reads traditional characters (財庫 → 财库) and
--    天之喜 → 天至喜, as the Phase 3 ready dates do.
--
