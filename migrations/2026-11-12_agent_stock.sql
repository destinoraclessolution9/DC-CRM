-- ── reads (as the caller: RLS decides whose stock) ───────────────────────────
-- One row per agent + product: in hand, lent to customers, owned (added − taken
-- out), the earliest office piece still owed back, and the last change.
create or replace function public.agent_stock_balance(p_agent bigint default null)
returns table (agent_id bigint, product_id bigint, item_name text, subcategory text,
               in_hand integer, lent_out integer, owned integer, next_back date,
               last_date date, last_kind text, last_qty integer)
language sql stable security invoker set search_path = public as $$
    with m as (
        select sm.*, coalesce(sm.product_id::text, 'n:' || public.agent_stock_flat(sm.item_name)) as gk
          from public.agent_stock_moves sm
         where p_agent is null or sm.agent_id = p_agent
    ),
    g as (
        select m.agent_id, m.gk, max(m.product_id) as product_id,
               sum(m.qty)::int as in_hand,
               coalesce(-sum(m.qty) filter (where m.kind in ('lent', 'returned', 'unlent')), 0)::int as lent_out,
               coalesce(sum(m.qty) filter (where m.kind in ('added', 'adjust')), 0)::int as owned
          from m group by m.agent_id, m.gk
    ),
    l as (
        select distinct on (m.agent_id, m.gk) m.agent_id, m.gk, m.move_date, m.kind, m.qty, m.item_name
          from m order by m.agent_id, m.gk, m.move_date desc, m.id desc
    ),
    b as (
        select m.agent_id, m.gk, min(da.expected_back) as next_back
          from m join public.delivery_advances da on da.id = m.advance_id
         where m.kind = 'lent' and da.status = 'owed' and da.lender_agent_id = m.agent_id
         group by m.agent_id, m.gk
    )
    select g.agent_id, g.product_id, coalesce(pr.name, l.item_name), pr.subcategory,
           g.in_hand, g.lent_out, g.owned, b.next_back, l.move_date, l.kind, l.qty
      from g
      join l on l.agent_id = g.agent_id and l.gk = g.gk
      left join b on b.agent_id = g.agent_id and b.gk = g.gk
      left join public.products pr on pr.id = g.product_id
     order by g.agent_id, pr.subcategory nulls last, coalesce(pr.name, l.item_name)
$$;

-- In-hand count per agent for the product a sold item is (the handover's
-- "Whose stock?" list). Only agents the caller may see.
create or replace function public.agent_stock_counts(p_item text)
returns table (agent_id bigint, product_id bigint, in_hand integer)
language sql stable security invoker set search_path = public as $$
    with p as (select public.agent_stock_product(p_item) as pid, public.agent_stock_flat(p_item) as fl)
    select sm.agent_id, p.pid, sum(sm.qty)::int
      from public.agent_stock_moves sm, p
     where (p.pid is not null and sm.product_id = p.pid)
        or (p.pid is null and sm.product_id is null and public.agent_stock_flat(sm.item_name) = p.fl)
     group by sm.agent_id, p.pid
$$;

