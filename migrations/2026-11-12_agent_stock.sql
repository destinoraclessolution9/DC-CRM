-- ── eligibility: traditional characters too ──────────────────────────────────
create or replace function public.delivery_advance_allowed(p_item text) returns boolean
language sql stable security definer set search_path = public as $$
    with t as (select replace(public.office_t2s(coalesce(p_item, '')), '天之喜', '天至喜') as s)
    select not public.journey_is_ring(t.s)
       and coalesce(public.journey_item_group(t.s), '') not like 'Fengshui%'
       and (coalesce(public.journey_item_group(t.s), '') in ('Calligraphy Adornment', 'Artistic Masterpieces', 'Royal Woodwork Series')
            or exists (select 1 from public.products pr
                        where pr.subcategory in ('Calligraphy Adornment', 'Artistic Masterpieces', 'Royal Woodwork Series')
                          and coalesce(pr.is_active, true) and public.pipeline_name_match(t.s, pr.name)))
      from t
$$;

-- ── names → one key (simplified, no brackets, no spaces, lower case) ────────
create or replace function public.agent_stock_flat(p text) returns text
language sql immutable set search_path = public as $$
    select lower(regexp_replace(regexp_replace(replace(public.office_t2s(coalesce(p, '')), '天之喜', '天至喜'),
                                               '[（(][^）)]*[）)]', '', 'g'), '[[:space:]　]+', '', 'g'))
$$;

-- The products an agent can hold: calligraphy / artistic / 财库·财托, active,
-- without the promo / launch-price copies (same piece, other price).
create or replace function public.agent_stock_products() returns table (id bigint, name text, subcategory text)
language sql stable security definer set search_path = public as $$
    select pr.id, pr.name, pr.subcategory from public.products pr
     where pr.subcategory in ('Calligraphy Adornment', 'Artistic Masterpieces', 'Royal Woodwork Series')
       and coalesce(pr.is_active, true)
       and pr.name !~* '(推介|特价|特惠|限时|promo)'
     order by pr.subcategory, pr.name
$$;

-- Which stock product a sold item is: the longest Chinese name (or a part of a
-- hyphenated name) found in the item wins; the English name is the fallback.
-- '新元亨利贞' → 新元亨利贞 (not 元亨利贞); '上龙柄（推介特价）' → 上龙柄;
-- 'BAO WANG XIANG 2' → 宝王象2. NULL when nothing fits.
create or replace function public.agent_stock_product(p_item text) returns bigint
language sql stable security definer set search_path = public as $$
    with f as (select public.agent_stock_flat(p_item) as s),
    c as (select p.id, regexp_replace(public.office_t2s(p.name), '[（(][^）)]*[）)]', '', 'g') as nm
            from public.agent_stock_products() p),
    k as (
        select c.id, 1 as pri, public.agent_stock_flat(trim(substring(c.nm from '^[^A-Za-z]+'))) as key from c
        union all
        select c.id, 1, public.agent_stock_flat(seg)
          from c, lateral regexp_split_to_table(trim(substring(c.nm from '^[^A-Za-z]+')), '[-－]') seg
        union all
        select c.id, 2, public.agent_stock_flat(substring(c.nm from '[A-Za-z][A-Za-z0-9 .]*$')) from c
    )
    select k.id from k, f
     where char_length(coalesce(k.key, '')) >= 2 and position(k.key in f.s) > 0
     order by k.pri, char_length(k.key) desc, k.id
     limit 1
$$;

-- ── the ledger ───────────────────────────────────────────────────────────────
create table if not exists public.agent_stock_moves (
    id          bigint generated by default as identity primary key,
    agent_id    bigint not null,
    product_id  bigint references public.products(id) on delete set null,
    item_name   text not null,
    qty         integer not null check (qty <> 0 and qty between -999 and 999),
    kind        text not null check (kind in ('added', 'adjust', 'lent', 'returned', 'unlent')),
    move_date   date not null default ((now() at time zone 'Asia/Kuala_Lumpur')::date),
    advance_id  bigint,              -- delivery_advances.id (kept after a delete, for history)
    note        text,
    created_by  bigint,
    created_at  timestamptz not null default now()
);
create index if not exists agent_stock_moves_agent on public.agent_stock_moves (agent_id, product_id);
create index if not exists agent_stock_moves_adv on public.agent_stock_moves (advance_id) where advance_id is not null;

-- Fill / guard: a product must be one an agent can hold; by hand only for an
-- existing user; who wrote it comes from the session.
create or replace function public.agent_stock_move_fill() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_name text;
begin
    if new.product_id is not null then
        select pr.name into v_name from public.products pr
         where pr.id = new.product_id and pr.subcategory in ('Calligraphy Adornment', 'Artistic Masterpieces', 'Royal Woodwork Series');
        if v_name is null then
            raise exception 'Only calligraphy, artistic masterpieces and 财库 / 财托 can be agent stock';
        end if;
        new.item_name := v_name;
    elsif new.kind in ('added', 'adjust') and not public.delivery_advance_allowed(coalesce(new.item_name, '')) then
        raise exception 'Only calligraphy, artistic masterpieces and 财库 / 财托 can be agent stock';
    end if;
    if not exists (select 1 from public.users u where u.id = new.agent_id) then
        raise exception 'Unknown agent';
    end if;
    new.created_by := coalesce(public.current_user_row_id(), new.created_by);
    return new;
end $$;
drop trigger if exists trg_agent_stock_move_fill on public.agent_stock_moves;
create trigger trg_agent_stock_move_fill before insert on public.agent_stock_moves
    for each row execute function public.agent_stock_move_fill();

-- Lent / returned / record removed: follows delivery_advances.
create or replace function public.agent_stock_from_advance() returns trigger
language plpgsql security definer set search_path = public as $$
declare r record; v_qty int; v_pid bigint; v_cust text; v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
begin
    if tg_op = 'DELETE' then r := old; else r := new; end if;
    select greatest(coalesce(di.qty, 1), 1) into v_qty from public.delivery_items di where di.id = r.delivery_item_id;
    v_qty := coalesce(v_qty, 1);
    v_pid := public.agent_stock_product(r.item_name);
    select c.full_name into v_cust from public.customers c where c.id = r.customer_id;
    v_cust := coalesce(v_cust, 'customer');

    if tg_op = 'INSERT' then
        insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
        values (new.lender_agent_id, v_pid, new.item_name, -v_qty, 'lent', coalesce(new.given_date, v_today), new.id, 'given to ' || v_cust);
        if new.status = 'returned' then
            insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
            values (new.lender_agent_id, v_pid, new.item_name, v_qty, 'returned', coalesce(new.returned_date, v_today), new.id, 'office piece back · ' || v_cust);
        end if;
    elsif tg_op = 'DELETE' then
        if old.status = 'owed' then
            insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
            values (old.lender_agent_id, v_pid, old.item_name, v_qty, 'unlent', v_today, old.id, 'record removed · ' || v_cust);
        end if;
    else
        if old.lender_agent_id is distinct from new.lender_agent_id then
            if old.status = 'owed' then
                insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
                values (old.lender_agent_id, v_pid, old.item_name, v_qty, 'unlent', v_today, old.id, 'moved to another agent · ' || v_cust);
            end if;
            if new.status = 'owed' then
                insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
                values (new.lender_agent_id, v_pid, new.item_name, -v_qty, 'lent', v_today, new.id, 'given to ' || v_cust);
            end if;
        elsif old.status = 'owed' and new.status = 'returned' then
            insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
            values (new.lender_agent_id, v_pid, new.item_name, v_qty, 'returned', coalesce(new.returned_date, v_today), new.id, 'office piece back · ' || v_cust);
        elsif old.status = 'returned' and new.status = 'owed' then
            insert into public.agent_stock_moves (agent_id, product_id, item_name, qty, kind, move_date, advance_id, note)
            values (new.lender_agent_id, v_pid, new.item_name, -v_qty, 'lent', v_today, new.id, 'return undone · ' || v_cust);
        end if;
    end if;
    return null;
end $$;
drop trigger if exists trg_agent_stock_from_advance on public.delivery_advances;
create trigger trg_agent_stock_from_advance after insert or delete or update of status, lender_agent_id on public.delivery_advances
    for each row execute function public.agent_stock_from_advance();

