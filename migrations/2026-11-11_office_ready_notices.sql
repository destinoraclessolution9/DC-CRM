-- =============================================================================
-- 2026-11-11_office_ready_notices.sql
-- 🏢 Office "ready for collection" notices (owner 2026-11-11, Phase 1).
--
-- The office (Agnes) sends a photo of a table — e.g. "財庫 pls collect on
-- 11 NOV 2026, WED - lvl 20" with SN NO | group | DEALER | CUSTOMER | ITEM.
-- Our side then: collects the pieces from the office → tells the customer →
-- the customer collects (the existing handover with photo proof).
--
--   office_notices       one row per uploaded photo (kept as the record)
--   office_notice_lines  every line the AI read off the photo
--   delivery_items       + office_ready_date/place/notice, collected_*, customer_told_*
--
-- delivery_items.status stays pending | delivered | picked_up — the handover
-- check (date + photo), Mark delivered, the 30-day reminder, the journey
-- triggers and the agent-stock advances all keep working unchanged. The new
-- columns are not in any trigger's "update of" list, so writing them does not
-- re-run journey_item_sync.
--
-- Matching is by SN = the order's invoice number (PR/PRN prefix dropped, other
-- prefixes such as "SG" kept). Office sheets cover the whole LIM CY group, so
-- lines that match nothing stay listed (decision 'not_ours' or untouched).
--
-- Staff only (level <= 12), same audience as delivery_items. Additive +
-- idempotent. Undo: 2026-11-11_office_ready_notices_UNDO.sql.
-- =============================================================================

-- ── SN normaliser ─────────────────────────────────────────────────────────────
-- "PR 1936760" → 1936760 · "PRN19018491" → 19018491 · "SG 0000013" → SG0000013
-- "1908016" → 1908016. Upper-case, only letters + digits, a leading PR / PRN in
-- front of a digit dropped.
create or replace function public.office_sn_norm(p text)
returns text
language sql
immutable
set search_path = public, pg_temp
as $$
  select nullif(regexp_replace(regexp_replace(upper(coalesce(p, '')), '[^A-Z0-9]', '', 'g'), '^PRN?([0-9])', '\1'), '');
$$;
grant execute on function public.office_sn_norm(text) to authenticated;

-- ── Notices + lines ──────────────────────────────────────────────────────────
create table if not exists public.office_notices (
  id            bigint generated by default as identity primary key,
  photo_path    text   not null,                 -- attachments bucket object path
  photo_hash    text,                            -- sha-256 of the original file (duplicate check)
  status        text   not null default 'saved'
                check (status in ('saved', 'read', 'applied', 'discarded')),
  is_ready_list boolean,
  title         text,
  category      text,
  collect_date  date,
  collect_time  text,
  place         text,
  read_provider text,
  read_error    text,
  read_at       timestamptz,
  created_by    bigint,
  created_at    timestamptz not null default now(),
  applied_by    bigint,
  applied_at    timestamptz,
  updated_at    timestamptz not null default now()
);
create unique index if not exists office_notices_hash_uq
  on public.office_notices (photo_hash) where photo_hash is not null and status <> 'discarded';
create index if not exists office_notices_created_idx on public.office_notices (created_at desc);

create table if not exists public.office_notice_lines (
  id               bigint generated by default as identity primary key,
  notice_id        bigint not null references public.office_notices(id) on delete cascade,
  line_no          integer not null,
  sn_raw           text,
  sn_norm          text,
  grp              text,
  dealer           text,
  customer         text,
  item             text,
  order_date       text,
  remarks          text,
  decision         text check (decision in ('apply', 'not_ours')),
  purchase_id      bigint,
  prospect_id      bigint,
  customer_id      bigint,
  delivery_item_id bigint,
  applied_at       timestamptz,
  created_at       timestamptz not null default now()
);
create index if not exists office_notice_lines_notice_idx on public.office_notice_lines (notice_id, line_no);
create index if not exists office_notice_lines_sn_idx on public.office_notice_lines (sn_norm);
create index if not exists office_notice_lines_item_idx on public.office_notice_lines (delivery_item_id);

-- keep sn_norm in step with sn_raw (an SN fixed on the review screen re-matches)
create or replace function public.office_notice_lines_norm()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  new.sn_norm := public.office_sn_norm(new.sn_raw);
  return new;
end;
$$;
drop trigger if exists office_notice_lines_norm on public.office_notice_lines;
create trigger office_notice_lines_norm before insert or update of sn_raw on public.office_notice_lines
  for each row execute function public.office_notice_lines_norm();

create or replace function public.office_notices_touch()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists office_notices_touch on public.office_notices;
create trigger office_notices_touch before update on public.office_notices
  for each row execute function public.office_notices_touch();

