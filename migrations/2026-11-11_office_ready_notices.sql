-- ── Candidates: every line of a notice + the CRM orders with the same SN ─────
-- SECURITY DEFINER so an agent's upload matches every team's orders (the office
-- sheet is group-wide and delivery_items is already staff-wide). Staff only.
create or replace function public.office_notice_candidates(p_notice_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare v jsonb;
begin
  if coalesce(public.current_user_level(), 99) > 12 then
    raise exception 'office notices are for staff only' using errcode = '42501';
  end if;
  with ord as (
    -- purchases (most orders)
    select 'purchase'::text as kind, p.id as order_id, p.customer_id, public.office_sn_norm(p.invoice) as sn_norm,
           p.invoice, p.item, p.date as order_date, coalesce(p.delivery_status, 'Pending Delivery') as delivery_status,
           coalesce(p.agent_id, c.responsible_agent_id) as agent_id, c.full_name as customer_name
      from public.purchases p
      -- a few sales carry only the prospect; the customer is the one converted from it
      join public.customers c on c.id = coalesce(p.customer_id,
             (select c2.id from public.customers c2 where c2.converted_from_prospect_id = p.prospect_id order by c2.id limit 1))
     where public.office_sn_norm(p.invoice) in (select l.sn_norm from public.office_notice_lines l where l.notice_id = p_notice_id)
    union all
    -- legacy conversion sale that only lives on the prospect's closing record
    select 'conversion', pr.id, c.id, public.office_sn_norm(pr.closing_record->>'invoice_number'),
           pr.closing_record->>'invoice_number', pr.closing_record->>'product',
           case when coalesce(pr.closing_record->>'order_date', '') ~ '^\d{4}-\d{2}-\d{2}$' then (pr.closing_record->>'order_date')::date end,
           coalesce(pr.closing_record->>'delivery_status', 'Pending Delivery'),
           c.responsible_agent_id, c.full_name
      from public.prospects pr
      join public.customers c on c.converted_from_prospect_id = pr.id
     where jsonb_typeof(pr.closing_record) = 'object'
       and public.office_sn_norm(pr.closing_record->>'invoice_number') in (select l.sn_norm from public.office_notice_lines l where l.notice_id = p_notice_id)
       and not exists (select 1 from public.purchases p2
                        where (p2.customer_id = c.id or p2.prospect_id = pr.id)
                          and public.office_sn_norm(p2.invoice) = public.office_sn_norm(pr.closing_record->>'invoice_number'))
  ),
  ord_json as (
    select o.sn_norm,
           jsonb_build_object(
             'kind', o.kind, 'id', o.order_id, 'customer_id', o.customer_id, 'customer_name', o.customer_name,
             'invoice', o.invoice, 'item', o.item, 'order_date', o.order_date, 'delivery_status', o.delivery_status,
             'agent_id', o.agent_id, 'agent_name', (select u.full_name from public.users u where u.id = o.agent_id),
             'items', coalesce((
               select jsonb_agg(jsonb_build_object(
                        'id', di.id, 'item_name', di.item_name, 'status', di.status,
                        'office_ready_date', di.office_ready_date, 'office_notice_id', di.office_notice_id,
                        'collected_at', di.collected_at, 'handover_date', di.handover_date,
                        'adv_status', a.status, 'adv_lender_id', a.lender_agent_id,
                        'adv_lender_name', (select u.full_name from public.users u where u.id = a.lender_agent_id))
                      order by di.id)
                 from public.delivery_items di
                 left join public.delivery_advances a on a.delivery_item_id = di.id
                where (o.kind = 'purchase' and di.purchase_id = o.order_id)
                   or (o.kind = 'conversion' and di.prospect_id = o.order_id)), '[]'::jsonb)
           ) as j
      from ord o
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', l.id, 'line_no', l.line_no, 'sn_raw', l.sn_raw, 'sn_norm', l.sn_norm, 'grp', l.grp,
           'dealer', l.dealer, 'customer', l.customer, 'item', l.item, 'order_date', l.order_date,
           'remarks', l.remarks, 'decision', l.decision, 'delivery_item_id', l.delivery_item_id,
           'applied_at', l.applied_at,
           'orders', coalesce((select jsonb_agg(oj.j) from ord_json oj where oj.sn_norm = l.sn_norm), '[]'::jsonb))
         order by l.line_no), '[]'::jsonb)
    into v
    from public.office_notice_lines l
   where l.notice_id = p_notice_id;
  return v;
end;
$$;
revoke all on function public.office_notice_candidates(bigint) from public, anon;
grant execute on function public.office_notice_candidates(bigint) to authenticated;

-- ── Apply: mark the picked items "ready at office" + push the agents ─────────
-- p_picks = [{ "line_id": 1, "kind": "purchase", "order_id": 9, "item_id": 5 }, …]
-- item_id null → a new item on that order (the office lists more pieces than
-- the CRM has; item_name = the office's item text). The order must carry the
-- line's SN, and the item must belong to that order.
create or replace function public.office_notice_apply(p_notice_id bigint, p_picks jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  n          record;
  pk         jsonb;
  l          record;
  v_me       bigint := public.current_user_row_id();
  v_kind     text;
  v_order    bigint;
  v_item     bigint;
  v_cust     bigint;
  v_name     text;
  v_ready    date;
  v_applied  int := 0;
  v_created  int := 0;
  v_pushed   int := 0;
  v_lines    bigint[] := '{}';
begin
  if coalesce(public.current_user_level(), 99) > 12 then
    raise exception 'office notices are for staff only' using errcode = '42501';
  end if;
  select * into n from public.office_notices where id = p_notice_id for update;
  if n.id is null then raise exception 'notice % not found', p_notice_id; end if;
  if n.status not in ('read', 'applied') then raise exception 'notice is %, not read yet', n.status; end if;
  v_ready := coalesce(n.collect_date, (n.created_at at time zone 'Asia/Kuala_Lumpur')::date);

  for pk in select * from jsonb_array_elements(coalesce(p_picks, '[]'::jsonb)) loop
    select * into l from public.office_notice_lines where id = (pk->>'line_id')::bigint and notice_id = p_notice_id;
    if l.id is null then raise exception 'line % is not on notice %', pk->>'line_id', p_notice_id; end if;
    if l.applied_at is not null then continue; end if;
    v_kind  := pk->>'kind';
    v_order := (pk->>'order_id')::bigint;
    v_item  := nullif(pk->>'item_id', '')::bigint;

    -- the order must carry this line's SN
    if v_kind = 'purchase' then
      select coalesce(p.customer_id,
               (select c.id from public.customers c where c.converted_from_prospect_id = p.prospect_id order by c.id limit 1))
        into v_cust from public.purchases p
       where p.id = v_order and public.office_sn_norm(p.invoice) = l.sn_norm;
    elsif v_kind = 'conversion' then
      select c.id into v_cust from public.prospects pr join public.customers c on c.converted_from_prospect_id = pr.id
       where pr.id = v_order and public.office_sn_norm(pr.closing_record->>'invoice_number') = l.sn_norm;
    else
      raise exception 'unknown order kind %', v_kind;
    end if;
    if v_cust is null then raise exception 'line % (SN %) does not match order %', l.line_no, l.sn_raw, v_order; end if;

    if v_item is null then
      v_name := left(coalesce(nullif(btrim(pk->>'item_name'), ''), nullif(btrim(l.item), ''),
                     (select nullif(btrim(p.item), '') from public.purchases p where v_kind = 'purchase' and p.id = v_order),
                     'Item'), 300);
      insert into public.delivery_items (customer_id, purchase_id, prospect_id, item_name, ring_size, created_by)
      values (v_cust,
              case when v_kind = 'purchase' then v_order end,
              case when v_kind = 'conversion' then v_order end,
              v_name,
              (select nullif(btrim(p.ring_size), '') from public.purchases p where v_kind = 'purchase' and p.id = v_order),
              v_me)
      returning id into v_item;
      v_created := v_created + 1;
    elsif not exists (select 1 from public.delivery_items di where di.id = v_item
                        and ((v_kind = 'purchase' and di.purchase_id = v_order) or (v_kind = 'conversion' and di.prospect_id = v_order))) then
      raise exception 'item % is not on order %', v_item, v_order;
    end if;

    update public.delivery_items
       set office_ready_date = v_ready, office_ready_place = n.place, office_notice_id = n.id
     where id = v_item;
    update public.office_notice_lines
       set decision = 'apply', applied_at = now(), delivery_item_id = v_item, customer_id = v_cust,
           purchase_id = case when v_kind = 'purchase' then v_order end,
           prospect_id = case when v_kind = 'conversion' then v_order end
     where id = l.id;
    v_applied := v_applied + 1;
    v_lines := v_lines || l.id;
  end loop;

  update public.office_notices set status = 'applied', applied_by = coalesce(applied_by, v_me), applied_at = coalesce(applied_at, now())
   where id = p_notice_id;

  -- One push per person for the lines applied in THIS call: the sale agent of
  -- each item, plus the lender when the customer already has the lender's own
  -- piece (the office piece goes back to them). Lands in notification_outbox;
  -- the dispatch job delivers it (bell when no phone is signed up).
  if cardinality(v_lines) = 0 then
    return jsonb_build_object('applied', 0, 'created', 0, 'pushed', 0);
  end if;
  insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
  select r.user_id, 'office_ready', 'normal',
         '🏢 Ready at office · ' || count(*) || ' item' || case when count(*) > 1 then 's' else '' end,
         'Collect ' || to_char(v_ready, 'FMDD Mon') || coalesce(' · ' || nullif(n.place, ''), '') || E'\n'
           || string_agg(r.line, E'\n' order by r.line),
         './index.html?delivery=1#customers',
         'office_ready:' || n.id || ':' || v_lines[1] || ':' || r.user_id,
         now()
    from (
      select distinct x.user_id, x.line
        from public.office_notice_lines ol
        join public.delivery_items di on di.id = ol.delivery_item_id
        join public.customers c on c.id = di.customer_id
        left join public.purchases p on p.id = di.purchase_id
        left join public.delivery_advances a on a.delivery_item_id = di.id and a.status = 'owed'
        cross join lateral (values
          (coalesce(p.agent_id, c.responsible_agent_id), left(c.full_name, 30) || ' · ' || left(di.item_name, 30)),
          (a.lender_agent_id, '🤝 ' || left(c.full_name, 30) || ' · ' || left(di.item_name, 30) || ' (your piece back)')
        ) as x(user_id, line)
       where ol.id = any(v_lines) and x.user_id is not null
    ) r
   group by r.user_id
  on conflict (user_id, dedupe_key) do nothing;
  get diagnostics v_pushed = row_count;

  return jsonb_build_object('applied', v_applied, 'created', v_created, 'pushed', v_pushed);
end;
$$;
revoke all on function public.office_notice_apply(bigint, jsonb) from public, anon;
grant execute on function public.office_notice_apply(bigint, jsonb) to authenticated;
