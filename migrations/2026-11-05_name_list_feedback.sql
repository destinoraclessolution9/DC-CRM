-- Name lists: "Not right?" feedback, to study and improve the suggestions (2026-11-05, owner).
--
-- Agents and leaders tell the CRM when a suggested name is wrong (pick what is
-- wrong + a comment, optionally taking them off the list), and why it missed a
-- person they add by hand. Each note keeps a copy of what the CRM saw at that
-- moment (scores, reasons, next step, the list's rule, items counted) so the
-- notes can be studied later against the engine. Nothing is learned
-- automatically — the rules change only after someone reads the notes.
--
--   name_list_feedback            append-only (no edits), one row per note
--   name_list_feedback(row, …)    save a note (+ take off) — who may work the row
--   name_list_feedback_report()   the Accuracy section: lists I manage + notes
--   name_list_get                 rows now carry their notes
--
-- Rollback: migrations/2026-11-05_name_list_feedback_undo.sql.

create table if not exists public.name_list_feedback (
    id            bigint generated by default as identity primary key,
    list_id       bigint not null references public.name_lists(id) on delete cascade,
    version_no    int not null,
    row_id        bigint,                    -- snapshot id (no FK: notes go with the list)
    person_key    text not null,
    name_snapshot text,
    agent_id      bigint,
    kind          text not null check (kind in ('wrong', 'missed')),
    reason        text not null check (reason in ('owns_more', 'not_interested', 'not_mine', 'bad_record', 'bad_timing',
                                                   'wrong_reason', 'should_match', 'not_recorded', 'referred', 'other')),
    note          text check (note is null or char_length(note) <= 500),
    engine        jsonb not null default '{}',   -- what the CRM saw when the note was written
    took_off      boolean not null default false,
    by_id         bigint references public.users(id),
    at            timestamptz not null default now()
);
create index if not exists nlf_list_person on public.name_list_feedback (list_id, person_key);
create index if not exists nlf_at on public.name_list_feedback (at desc);
alter table public.name_list_feedback enable row level security;
revoke all on public.name_list_feedback from anon, authenticated;

create or replace function public.nl_feedback_guard() returns trigger
language plpgsql set search_path = public as $$
begin
    raise exception 'Feedback notes cannot be edited';
end $$;
drop trigger if exists name_list_feedback_guard on public.name_list_feedback;
create trigger name_list_feedback_guard before update on public.name_list_feedback
    for each row execute function public.nl_feedback_guard();

create or replace function public.nl_fb_label(p_reason text) returns text
language sql immutable as $$
    select case p_reason
        when 'owns_more' then 'Already owns more than shown'
        when 'not_interested' then 'Not interested / not suitable'
        when 'not_mine' then 'Not my customer / wrong agent'
        when 'bad_record' then 'Record is wrong (duplicate, bought for someone else)'
        when 'bad_timing' then 'Bad timing (just bought, just contacted)'
        when 'wrong_reason' then 'The reason shown is wrong'
        when 'should_match' then 'Should have matched'
        when 'not_recorded' then 'Interested, but not recorded in the CRM'
        when 'referred' then 'Referred / new contact'
        else 'Other' end
$$;

-- Save a note on a row. Engine rows → "wrong" (what is wrong); rows added by
-- hand → "missed" (why the CRM missed them). Take off = the normal remove,
-- with the note as its reason text.
create or replace function public.name_list_feedback(p_row bigint, p_reason text, p_note text default null, p_take_off boolean default false)
returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Kuala_Lumpur' as $$
declare
    v_me bigint := public.current_user_row_id(); r public.name_list_rows; l public.name_lists;
    v_kind text; v_note text; v_no int; v_off boolean := false; v_owned int; v_id bigint;
begin
    if v_me is null or not public.nl_can_act(p_row) then raise exception 'Not permitted' using errcode = '42501'; end if;
    select * into r from public.name_list_rows where id = p_row;
    select * into l from public.name_lists where id = r.list_id;
    v_kind := case when r.source = 'manual' then 'missed' else 'wrong' end;
    if v_kind = 'wrong' and coalesce(p_reason, '') not in ('owns_more', 'not_interested', 'not_mine', 'bad_record', 'bad_timing', 'wrong_reason', 'other') then
        raise exception 'Pick what is wrong';
    end if;
    if v_kind = 'missed' and coalesce(p_reason, '') not in ('should_match', 'not_recorded', 'referred', 'other') then
        raise exception 'Pick why the CRM missed them';
    end if;
    v_note := left(nullif(btrim(coalesce(p_note, '')), ''), 500);
    if p_reason = 'other' and v_note is null then raise exception 'Write a short comment'; end if;
    select version_no into v_no from public.name_list_versions where id = r.version_id;
    if coalesce(l.who, 'best') <> 'best' and l.line <> 'general' then
        select sum(s.items)::int into v_owned from public.nl_line_sales(l.line) s where s.person_key = r.person_key;
    end if;

    if coalesce(p_take_off, false) and v_kind = 'wrong' and r.decision <> 'removed' then
        perform public.name_list_decide(p_row, 'removed',
            case p_reason when 'not_mine' then 'wrong_person' when 'bad_record' then 'wrong_person' when 'other' then 'other' else 'not_fit' end,
            left('Not right — ' || public.nl_fb_label(p_reason) || coalesce(': ' || v_note, ''), 500));
        v_off := true;
    end if;

    insert into public.name_list_feedback (list_id, version_no, row_id, person_key, name_snapshot, agent_id, kind, reason, note,
                                           engine, took_off, by_id)
    values (r.list_id, v_no, r.id, r.person_key, r.name_snapshot, r.agent_id, v_kind, p_reason, v_note,
            jsonb_build_object(
                'fit', r.fit, 'engagement', r.engagement, 'readiness', r.readiness, 'grp', r.grp, 'rank', r.rank,
                'reasons', r.reasons, 'warnings', r.warnings, 'last_touch', r.last_touch,
                'next_step', r.next_step, 'next_step_rule', r.next_step_rule,
                'source', r.source, 'decision', r.decision, 'engine_picked', r.engine_picked,
                'line', l.line, 'goal', l.goal, 'who', l.who, 'focus', l.focus, 'scope', l.scope,
                'owned', v_owned, 'version', v_no),
            v_off, v_me)
    returning id into v_id;
    return jsonb_build_object('ok', true, 'id', v_id, 'took_off', v_off);
end $$;
revoke execute on function public.name_list_feedback(bigint, text, text, boolean) from public, anon;
grant execute on function public.name_list_feedback(bigint, text, text, boolean) to authenticated;
revoke execute on function public.nl_fb_label(text) from public, anon, authenticated;
revoke execute on function public.nl_feedback_guard() from public, anon, authenticated;

-- The Accuracy section: lists I manage (owner, their uplines, L1–2) and every
-- note on them, newest first (up to 500). {lists: [...], notes: [...]}
create or replace function public.name_list_feedback_report()
returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Kuala_Lumpur' as $$
declare v_me bigint := public.current_user_row_id(); v_lists jsonb; v_notes jsonb;
begin
    if v_me is null then raise exception 'Not permitted' using errcode = '42501'; end if;
    drop table if exists _nlf_lists;
    create temp table _nlf_lists on commit drop as
    select l.id, l.name, l.status, l.line, l.goal, l.who, l.created_at, public.nl_latest_version(l.id) ver
      from public.name_lists l where public.nl_can_manage(l.id);

    select coalesce(jsonb_agg(jsonb_build_object(
               'id', m.id, 'name', m.name, 'status', m.status, 'line', m.line,
               'line_label', (select label from public.invite_lines where key = m.line), 'goal', m.goal, 'who', m.who,
               'suggested', (select count(*) from public.name_list_rows r where r.version_id = m.ver and r.source <> 'manual'),
               'kept', (select count(*) from public.name_list_rows r where r.version_id = m.ver and r.source <> 'manual' and r.decision = 'selected'),
               'added', (select count(*) from public.name_list_rows r where r.version_id = m.ver and r.source = 'manual'),
               'wrong', (select count(*) from public.name_list_feedback f where f.list_id = m.id and f.kind = 'wrong'),
               'missed', (select count(*) from public.name_list_feedback f where f.list_id = m.id and f.kind = 'missed'),
               'by_reason', (select coalesce(jsonb_object_agg(z.reason, z.n), '{}'::jsonb)
                               from (select f.reason, count(*) n from public.name_list_feedback f where f.list_id = m.id group by f.reason) z))
             order by m.created_at desc, m.id desc), '[]'::jsonb)
      into v_lists from _nlf_lists m;

    select coalesce(jsonb_agg(jsonb_build_object(
               'list_id', f.list_id, 'list', m.name, 'version', f.version_no, 'name', f.name_snapshot, 'person_key', f.person_key,
               'agent', au.full_name, 'kind', f.kind, 'reason', f.reason, 'label', public.nl_fb_label(f.reason), 'note', f.note,
               'took_off', f.took_off, 'by', bu.full_name, 'at', f.at,
               'fit', f.engine -> 'fit', 'owned', f.engine -> 'owned', 'rule', f.engine ->> 'next_step_rule',
               'crm_said', (select coalesce(jsonb_agg(x ->> 't'), '[]'::jsonb)
                              from (select x from jsonb_array_elements(coalesce(f.engine -> 'reasons', '[]'::jsonb)) x limit 3) y))
             order by f.at desc, f.id desc), '[]'::jsonb)
      into v_notes
      from (select * from public.name_list_feedback where list_id in (select id from _nlf_lists) order by at desc, id desc limit 500) f
      join _nlf_lists m on m.id = f.list_id
      left join public.users au on au.id = f.agent_id
      left join public.users bu on bu.id = f.by_id;
    return jsonb_build_object('lists', v_lists, 'notes', v_notes);
end $$;
revoke execute on function public.name_list_feedback_report() from public, anon;
grant execute on function public.name_list_feedback_report() to authenticated;

-- One list: header, versions, rows (viewer-scoped) with live progress + notes.
create or replace function public.name_list_get(p_list bigint, p_version int default null)
returns jsonb language plpgsql security definer set search_path = public set timezone to 'Asia/Kuala_Lumpur' as $$
declare
    v_me bigint := public.current_user_row_id(); l public.name_lists; v public.name_list_versions;
    v_latest int; v_all boolean; v_rows jsonb; v_vers jsonb; v_cfg jsonb := public.nl_cfg();
begin
    if v_me is null then raise exception 'Not permitted' using errcode = '42501'; end if;
    select * into l from public.name_lists where id = p_list;
    if l.id is null or not public.nl_can_see(p_list) then raise exception 'Not permitted' using errcode = '42501'; end if;
    perform public.nl_claim_sales();
    select max(version_no) into v_latest from public.name_list_versions where list_id = p_list;
    select * into v from public.name_list_versions where list_id = p_list and version_no = coalesce(p_version, v_latest);
    if v.id is null then raise exception 'No such version'; end if;
    v_all := public.nl_can_manage(p_list);

    select coalesce(jsonb_agg(jsonb_build_object(
               'id', r.id, 'person_key', r.person_key, 'prospect_id', r.prospect_id, 'customer_id', r.customer_id,
               'name', r.name_snapshot, 'agent_id', r.agent_id, 'agent_name', r.agent_name_snapshot,
               'fit', r.fit, 'engagement', r.engagement, 'readiness', r.readiness, 'grp', r.grp, 'rank', r.rank,
               'reasons', r.reasons, 'warnings', r.warnings, 'last_touch', r.last_touch, 'engine_picked', r.engine_picked,
               'next_step', r.next_step, 'next_step_why', r.next_step_why, 'next_step_rule', r.next_step_rule, 'source', r.source,
               'added_by_name', ab.full_name, 'add_note', r.add_note,
               'decision', r.decision, 'decision_reason', r.decision_reason, 'decision_note', r.decision_note,
               'decided_by_name', db.full_name, 'decided_at', r.decided_at,
               'contact_at', x.contact_at, 'contact_via', x.contact_via, 'contact_auto', x.contact_auto,
               'reply', x.reply, 'reply_at', x.reply_at, 'reply_note', x.reply_note, 'met_at', x.met_at, 'met_via', x.met_via,
               'sale_amount', x.sale_amount, 'sale_date', x.sale_date, 'sale_item', x.sale_item,
               'freq', x.freq, 'dni', x.dni, 'phone', x.phone, 'prefers_call', x.prefers_call,
               'feedback', (select coalesce(jsonb_agg(jsonb_build_object('kind', f.kind, 'reason', f.reason, 'note', f.note,
                                                                         'by', fu.full_name, 'at', f.at, 'took_off', f.took_off)
                                                      order by f.at desc, f.id desc), '[]'::jsonb)
                              from public.name_list_feedback f left join public.users fu on fu.id = f.by_id
                             where f.list_id = p_list and f.person_key = r.person_key))
             order by case r.decision when 'selected' then 0 when 'pending' then 1 else 2 end,
                      r.agent_name_snapshot nulls last, r.rank nulls last, r.id), '[]'::jsonb)
      into v_rows
      from public.name_list_rows r
      join public.nl_live(p_list, v.id) x on x.row_id = r.id
      left join public.users ab on ab.id = r.added_by
      left join public.users db on db.id = r.decided_by
     where r.version_id = v.id and (v_all or r.agent_id in (select public.current_user_visible_ids()));

    select coalesce(jsonb_agg(jsonb_build_object('no', vv.version_no, 'generated_at', vv.generated_at, 'by', gu.full_name,
                                                 'picked', vv.picked, 'offered', vv.offered, 'held', vv.held, 'candidates', vv.candidates)
                              order by vv.version_no desc), '[]'::jsonb)
      into v_vers
      from public.name_list_versions vv left join public.users gu on gu.id = vv.generated_by
     where vv.list_id = p_list;

    return jsonb_build_object(
        'list', jsonb_build_object(
            'id', l.id, 'name', l.name, 'purpose', l.purpose, 'line', l.line,
            'line_label', (select label from public.invite_lines where key = l.line), 'goal', l.goal, 'focus', l.focus,
            'focus_names', (select coalesce(jsonb_agg(pr.name order by pr.id), '[]'::jsonb) from public.products pr
                             where pr.id in (select (f #>> '{}')::bigint from jsonb_array_elements(l.focus) f)),
            'scope', l.scope, 'status', l.status, 'target_qty', l.target_qty, 'target_date', l.target_date, 'remarks', l.remarks,
            'who', l.who, 'bought_from', l.bought_from, 'bought_to', l.bought_to, 'offer', l.offer,
            'owner_id', l.owner_id, 'owner_name', (select full_name from public.users where id = l.owner_id),
            'created_at', l.created_at, 'started_at', l.started_at, 'mine', l.owner_id = v_me, 'can_manage', v_all),
        'version', jsonb_build_object('no', v.version_no, 'latest', v.version_no = v_latest, 'generated_at', v.generated_at,
                                      'held', v.held, 'candidates', v.candidates, 'offered', v.offered, 'picked', v.picked),
        'versions', v_vers,
        'counts', public.nl_counts(p_list, v.id, v_all),
        'freq_limit', coalesce((v_cfg ->> 'freq_limit')::int, 2), 'freq_days', coalesce((v_cfg ->> 'freq_days')::int, 30),
        'rows', v_rows);
end $$;
