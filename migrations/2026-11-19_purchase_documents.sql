-- ═══════════════════════════════════════════════════════════════════════════
-- Payment documents: up to 50 files (receipts, photos, PDFs) per installment sale
-- (owner 2026-11-19). When an installment lapses the customer banks in and the
-- receipt must be kept — one pool per sale, shown from Product Delivery Listing.
--   · ref_kind 'purchase'   → ref_id = purchases.id
--     ref_kind 'conversion' → ref_id = prospects.id (sale kept in closing_record)
--   · hard cap of 50 enforced by a trigger (cannot be bypassed from the UI)
--   · files live in storage bucket `attachments` under purchase-docs/<kind>/<id>/
--   · a file can also be used as a POP lapse receipt (same storage path)
-- Additive only: new table, no existing object is changed.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists public.purchase_documents (
    id          bigint generated by default as identity primary key,
    ref_kind    text   not null check (ref_kind in ('purchase', 'conversion')),
    ref_id      bigint not null,
    customer_id bigint references public.customers(id) on delete set null,
    agent_id    bigint,
    file_path   text   not null,
    file_name   text,
    mime        text,
    size_bytes  integer,
    note        text,
    uploaded_by bigint,
    created_at  timestamptz not null default now()
);
create index if not exists purchase_documents_ref on public.purchase_documents (ref_kind, ref_id);
create index if not exists purchase_documents_path on public.purchase_documents (file_path);

-- fill agent/uploader server-side + enforce the 50-file cap (serialised per sale)
create or replace function public.purchase_documents_bi() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_n int; v_agent bigint; v_cust bigint;
begin
    perform pg_advisory_xact_lock(hashtext('purchase_documents:' || new.ref_kind || ':' || new.ref_id));
    select count(*) into v_n from public.purchase_documents where ref_kind = new.ref_kind and ref_id = new.ref_id;
    if v_n >= 50 then
        raise exception 'This sale already has 50 documents (the maximum). Delete one first.';
    end if;
    if new.ref_kind = 'purchase' then
        select pu.customer_id, pu.agent_id into v_cust, v_agent from public.purchases pu where pu.id = new.ref_id;
    end if;
    new.customer_id := coalesce(new.customer_id, v_cust);
    if v_agent is null and new.customer_id is not null then
        select c.responsible_agent_id into v_agent from public.customers c where c.id = new.customer_id;
    end if;
    new.agent_id := coalesce(v_agent, new.agent_id);
    new.uploaded_by := coalesce(public.current_user_row_id(), new.uploaded_by);
    return new;
end $$;
drop trigger if exists trg_purchase_documents_bi on public.purchase_documents;
create trigger trg_purchase_documents_bi before insert on public.purchase_documents
    for each row execute function public.purchase_documents_bi();

alter table public.purchase_documents enable row level security;

drop policy if exists purchase_documents_sel on public.purchase_documents;
create policy purchase_documents_sel on public.purchase_documents for select to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or agent_id in (select public.current_user_visible_ids()) or agent_id = public.current_user_row_id()
    or public.customer_is_visible(customer_id));

-- add: the sale's agent, their leaders, admin (same rule as POP lapses)
drop policy if exists purchase_documents_ins on public.purchase_documents;
create policy purchase_documents_ins on public.purchase_documents for insert to authenticated
    with check (public.pop_can_act(agent_id));

-- edit the note: same people
drop policy if exists purchase_documents_upd on public.purchase_documents;
create policy purchase_documents_upd on public.purchase_documents for update to authenticated
    using (public.pop_can_act(agent_id)) with check (public.pop_can_act(agent_id));

-- delete: admin, or the person who uploaded it
drop policy if exists purchase_documents_del on public.purchase_documents;
create policy purchase_documents_del on public.purchase_documents for delete to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or uploaded_by = public.current_user_row_id());

revoke all on public.purchase_documents from public, anon;
grant select, insert, update, delete on public.purchase_documents to authenticated;
