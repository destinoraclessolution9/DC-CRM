-- =============================================================================
-- event_session_media_2026-10-15.sql
-- 活动照片 · Event Photos & Video — per-session media on the event Activity Details.
--
-- Keyed by (event_id, session_date) like events.event_roles, so every agent's
-- activity row for the same event + date shows the same media.
--   * kind 'photo'      → url = attachments-bucket public URL (resolved to a signed
--                         URL client-side; the bucket is private).
--   * kind 'video_link' → url = Google Drive / YouTube link (no CRM storage).
-- Caps per session: 10 photos, 1 video link — enforced in add_event_session_media
-- under an advisory lock so two agents uploading at once can't overshoot.
--
-- Scoping:
--   SELECT  = agent band + admins (level <= 12); customers/referrers never see it.
--   INSERT  = add_event_session_media RPC only (level <= 12).
--   DELETE  = delete_event_session_media RPC only: the uploader, anyone holding a
--             活动负责人 role for that session, or level <= 2 (admin / marketing mgr).
-- Additive only.
-- =============================================================================

create table if not exists public.event_session_media (
  id               bigint generated by default as identity primary key,
  event_id         bigint not null references public.events(id) on delete cascade,
  session_date     date   not null,
  kind             text   not null check (kind in ('photo', 'video_link')),
  url              text   not null,
  uploaded_by      bigint references public.users(id),
  uploaded_by_name text,
  created_at       timestamptz not null default now()
);

create index if not exists event_session_media_session_idx
  on public.event_session_media (event_id, session_date);

alter table public.event_session_media enable row level security;

drop policy if exists esm_select_agents on public.event_session_media;
create policy esm_select_agents on public.event_session_media
  for select to authenticated
  using (coalesce(public.current_user_level(), 99) <= 12);

-- No insert/update/delete policies: writes go through the RPCs below.
grant select on public.event_session_media to authenticated;
grant all on public.event_session_media to service_role;

-- ── Add ─────────────────────────────────────────────────────────────────────
create or replace function public.add_event_session_media(
  p_event_id     bigint,
  p_session_date text,
  p_kind         text,
  p_url          text
) returns public.event_session_media
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_me    bigint  := public.current_user_row_id();
  v_level integer := public.current_user_level();
  v_name  text;
  v_count integer;
  v_row   public.event_session_media;
begin
  if v_me is null or coalesce(v_level, 99) > 12 then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if p_kind not in ('photo', 'video_link') then
    raise exception 'invalid media kind: %', p_kind using errcode = '22023';
  end if;
  if p_session_date is null or p_session_date !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then
    raise exception 'invalid session date: %', p_session_date using errcode = '22023';
  end if;
  if p_url is null or p_url !~ '^https://' or length(p_url) > 2000 then
    raise exception 'invalid url' using errcode = '22023';
  end if;
  if not exists (select 1 from public.events where id = p_event_id) then
    raise exception 'event not found: %', p_event_id using errcode = 'P0002';
  end if;

  -- Serialise adds per session so the cap check + insert is atomic.
  perform pg_advisory_xact_lock(hashtext('esm:' || p_event_id || ':' || p_session_date));

  select count(*) into v_count
    from public.event_session_media
   where event_id = p_event_id and session_date = p_session_date::date and kind = p_kind;
  if p_kind = 'photo' and v_count >= 10 then
    raise exception '最多 10 张照片 · Max 10 photos per event date' using errcode = '23514';
  end if;
  if p_kind = 'video_link' and v_count >= 1 then
    raise exception '每场活动只能 1 个视频 · Only 1 video per event date' using errcode = '23514';
  end if;

  select full_name into v_name from public.users where id = v_me;

  insert into public.event_session_media (event_id, session_date, kind, url, uploaded_by, uploaded_by_name)
  values (p_event_id, p_session_date::date, p_kind, p_url, v_me, v_name)
  returning * into v_row;
  return v_row;
end;
$$;

revoke all on function public.add_event_session_media(bigint, text, text, text) from public;
grant execute on function public.add_event_session_media(bigint, text, text, text) to authenticated, service_role;

-- ── Delete ──────────────────────────────────────────────────────────────────
-- Returns the deleted row (the client uses url to best-effort remove the file).
create or replace function public.delete_event_session_media(p_id bigint)
returns public.event_session_media
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_me    bigint  := public.current_user_row_id();
  v_level integer := public.current_user_level();
  v_row   public.event_session_media;
  v_roles jsonb;
  v_ok    boolean := false;
begin
  if v_me is null then
    raise exception 'not allowed' using errcode = '42501';
  end if;

  select * into v_row from public.event_session_media where id = p_id;
  if not found then
    raise exception 'media not found: %', p_id using errcode = 'P0002';
  end if;

  if v_row.uploaded_by = v_me or coalesce(v_level, 99) <= 2 then
    v_ok := true;
  else
    -- Any 活动负责人 role holder for this session (主要负责人, 场地负责人,
    -- 报到负责人 1/2, 主讲老师, 活动司仪).
    select event_roles -> to_char(v_row.session_date, 'YYYY-MM-DD')
      into v_roles
      from public.events where id = v_row.event_id;
    if v_roles is not null and jsonb_typeof(v_roles) = 'object' then
      select exists (
        select 1 from jsonb_each(v_roles) r
         where jsonb_typeof(r.value) = 'object'
           and r.value ->> 'id' = v_me::text
      ) into v_ok;
    end if;
  end if;

  if not v_ok then
    raise exception '只有上传者、活动负责人或管理员可以删除 · Only the uploader, the event team or an admin can remove this'
      using errcode = '42501';
  end if;

  delete from public.event_session_media where id = p_id;
  return v_row;
end;
$$;

revoke all on function public.delete_event_session_media(bigint) from public;
grant execute on function public.delete_event_session_media(bigint) to authenticated, service_role;

notify pgrst, 'reload schema';
