-- ═══════════════════════════════════════════════════════════════════════════
-- POP: auto-deduct by default, track only LAPSED charges + manual receipts
-- (owner 2026-10-21)
--
-- POP charges are deducted from the customer's card automatically — nobody
-- ticks normal months. Only when a deduction lapses does the office tell the
-- agent; the customer banks in manually and sends a receipt that must be kept.
--   · each charge becomes "auto" (auto-deducted) once its date passes
--   · the AGENT (or their team leader / admin) marks a charge "lapsed"
--   · settled with a receipt (photo/PDF) → "paid_manual"; one receipt can cover
--     several lapsed months, the amount may differ (late fee); no approval step
--   · the card keeps deducting the following months
--   · tracked from October 2026 (earlier months stay "assumed", counted paid)
--   · reminder to the agent every 3 days while a charge is lapsed; 📋 top-5 row
--   · the 1st-of-month "charges due" push is retired
-- ═══════════════════════════════════════════════════════════════════════════

-- ── statuses ────────────────────────────────────────────────────────────────
alter table public.pop_installments drop constraint if exists pop_installments_status_check;
update public.pop_installments set status = 'lapsed' where status = 'failed';
update public.pop_installments set status = 'auto' where status = 'paid';
alter table public.pop_installments add constraint pop_installments_status_check
    check (status in ('due', 'auto', 'lapsed', 'paid_manual', 'waived', 'assumed'));
alter table public.pop_installments
    add column if not exists lapsed_at  date,
    add column if not exists lapsed_by  bigint,
    add column if not exists receipt_id bigint;

-- tracking starts October 2026; everything already due counts as auto-deducted
update public.pop_installments set status = 'auto', note = null
 where status = 'assumed' and due_date >= date '2026-10-01';
update public.pop_installments set status = 'auto'
 where status = 'due' and due_date < (now() at time zone 'Asia/Kuala_Lumpur')::date;

drop policy if exists pop_inst_upd on public.pop_installments;
create policy pop_inst_upd on public.pop_installments for update to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or agent_id in (select public.current_user_visible_ids()) or agent_id = public.current_user_row_id())
    with check (status in ('due', 'auto', 'lapsed', 'waived'));   -- paid_manual only via pop_record_receipt

create or replace function public.pop_inst_touch() returns trigger
language plpgsql as $$
begin
    new.updated_at := now();
    new.updated_by := coalesce(public.current_user_row_id(), new.updated_by);
    if new.status = 'lapsed' and old.status <> 'lapsed' then
        new.lapsed_at := coalesce(new.lapsed_at, (now() at time zone 'Asia/Kuala_Lumpur')::date);
        new.lapsed_by := coalesce(public.current_user_row_id(), new.lapsed_by);
    end if;
    -- un-marking a lapse (back to auto / due) clears it; paid_manual keeps the history
    if new.status in ('auto', 'due') and old.status = 'lapsed' then
        new.lapsed_at := null; new.lapsed_by := null;
    end if;
    if new.status <> 'paid_manual' then new.receipt_id := null; new.paid_date := null; end if;
    return new;
end $$;

-- ── receipts ────────────────────────────────────────────────────────────────
create table if not exists public.pop_receipts (
    id          bigint generated by default as identity primary key,
    purchase_id bigint not null references public.purchases(id) on delete cascade,
    customer_id bigint references public.customers(id) on delete set null,
    agent_id    bigint,
    paid_date   date not null,
    amount      numeric not null check (amount > 0),
    file_path   text not null,
    file_name   text,
    bank_ref    text,
    note        text,
    uploaded_by bigint,
    created_at  timestamptz not null default now()
);
create index if not exists pop_receipts_purchase on public.pop_receipts (purchase_id);
alter table public.pop_receipts enable row level security;
drop policy if exists pop_receipts_sel on public.pop_receipts;
create policy pop_receipts_sel on public.pop_receipts for select to authenticated using (
    coalesce(public.current_user_level(), 99) <= 2
    or agent_id in (select public.current_user_visible_ids()) or agent_id = public.current_user_row_id()
    or public.customer_is_visible(customer_id));
grant select on public.pop_receipts to authenticated;

-- may the viewer act on this sale's charges? (agent, their leaders, admin)
create or replace function public.pop_can_act(p_agent bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select coalesce(public.current_user_level(), 99) <= 2
        or p_agent = public.current_user_row_id()
        or p_agent in (select public.current_user_visible_ids())
$$;

-- Record a manual bank-in: one receipt for one or more lapsed months of ONE sale.
create or replace function public.pop_record_receipt(p_inst_ids bigint[], p_paid_date date, p_amount numeric,
    p_file_path text, p_file_name text default null, p_bank_ref text default null, p_note text default null)
returns bigint
language plpgsql security definer set search_path = public as $$
declare v_pu bigint; v_cust bigint; v_agent bigint; v_n int; v_id bigint;
begin
    if p_file_path is null or p_file_path = '' then raise exception 'The receipt is required'; end if;
    if p_amount is null or p_amount <= 0 then raise exception 'Enter the amount paid'; end if;
    if p_paid_date is null or p_paid_date > (now() at time zone 'Asia/Kuala_Lumpur')::date then raise exception 'Enter the date paid (not in the future)'; end if;
    select min(purchase_id), max(purchase_id), max(customer_id), max(agent_id), count(*) into v_pu, v_id, v_cust, v_agent, v_n
      from public.pop_installments where id = any (p_inst_ids) and status = 'lapsed';
    if v_n is null or v_n = 0 or v_n <> coalesce(array_length(p_inst_ids, 1), 0) then
        raise exception 'Only lapsed months can be paid manually';
    end if;
    if v_pu <> v_id then raise exception 'One receipt covers one sale at a time'; end if;
    if not public.pop_can_act(v_agent) then raise exception 'Not allowed for this customer'; end if;
    insert into public.pop_receipts (purchase_id, customer_id, agent_id, paid_date, amount, file_path, file_name, bank_ref, note, uploaded_by)
    values (v_pu, v_cust, v_agent, p_paid_date, p_amount, p_file_path, p_file_name, nullif(p_bank_ref, ''), nullif(p_note, ''), public.current_user_row_id())
    returning id into v_id;
    -- bypass the "paid_manual only via this function" check: we are this function
    update public.pop_installments set status = 'paid_manual' where id = any (p_inst_ids);
    update public.pop_installments set receipt_id = v_id, paid_date = p_paid_date where id = any (p_inst_ids);
    return v_id;
end $$;
revoke all on function public.pop_record_receipt(bigint[], date, numeric, text, text, text, text) from public, anon;
grant execute on function public.pop_record_receipt(bigint[], date, numeric, text, text, text, text) to authenticated;

-- the touch trigger clears receipt_id unless paid_manual — set both in one go
create or replace function public.pop_inst_touch() returns trigger
language plpgsql as $$
begin
    new.updated_at := now();
    new.updated_by := coalesce(public.current_user_row_id(), new.updated_by);
    if new.status = 'lapsed' and old.status <> 'lapsed' then
        new.lapsed_at := coalesce(new.lapsed_at, (now() at time zone 'Asia/Kuala_Lumpur')::date);
        new.lapsed_by := coalesce(public.current_user_row_id(), new.lapsed_by);
    end if;
    if new.status in ('auto', 'due') and old.status = 'lapsed' then
        new.lapsed_at := null; new.lapsed_by := null;
    end if;
    if new.status <> 'paid_manual' then new.receipt_id := null; new.paid_date := null; end if;
    return new;
end $$;

-- Undo a receipt recorded by mistake: its months go back to lapsed (file kept in storage).
create or replace function public.pop_undo_receipt(p_receipt_id bigint) returns boolean
language plpgsql security definer set search_path = public as $$
declare r record;
begin
    select * into r from public.pop_receipts where id = p_receipt_id;
    if r.id is null then return false; end if;
    if not (coalesce(public.current_user_level(), 99) <= 2 or r.uploaded_by = public.current_user_row_id()) then
        raise exception 'Only the person who uploaded it (or admin) can undo a receipt';
    end if;
    update public.pop_installments set status = 'lapsed' where receipt_id = p_receipt_id;
    delete from public.pop_receipts where id = p_receipt_id;
    return true;
end $$;
revoke all on function public.pop_undo_receipt(bigint) from public, anon;
grant execute on function public.pop_undo_receipt(bigint) to authenticated;

-- ── schedule builder: new rule (assumed < Oct 2026 · auto when past · due ahead) ──
create or replace function public.pop_plan_sync(p_purchase bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare
    pu record; tm record; k int; v_due date; v_n int := 0; v_cust bigint; v_agent bigint;
    v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date;
begin
    select * into pu from public.purchases where id = p_purchase;
    if pu.id is null then return 0; end if;
    tm := public.pop_plan_terms(p_purchase);
    if not coalesce(tm.is_plan, false) then
        delete from public.pop_installments where purchase_id = p_purchase and status in ('due', 'auto', 'assumed');
        return 0;
    end if;
    if exists (select 1 from public.pop_installments where purchase_id = p_purchase)
       and not exists (select 1 from public.pop_installments where purchase_id = p_purchase and status in ('lapsed', 'paid_manual', 'waived'))
       and ((select count(*) from public.pop_installments where purchase_id = p_purchase) <> tm.tenure
            or exists (select 1 from public.pop_installments where purchase_id = p_purchase and amount <> tm.monthly)
            or exists (select 1 from public.pop_installments where purchase_id = p_purchase and seq = 1
                        and due_date <> (pu.date + interval '1 month')::date)) then
        delete from public.pop_installments where purchase_id = p_purchase;
    end if;
    v_cust := coalesce(pu.customer_id, (select c.id from public.customers c where c.converted_from_prospect_id = pu.prospect_id limit 1));
    v_agent := coalesce(pu.agent_id, (select responsible_agent_id from public.customers where id = v_cust));
    if exists (select 1 from public.pop_installments where purchase_id = p_purchase) then
        update public.pop_installments set customer_id = v_cust, agent_id = v_agent
         where purchase_id = p_purchase and (customer_id is distinct from v_cust or agent_id is distinct from v_agent);
        return 0;
    end if;
    for k in 1 .. tm.tenure loop
        v_due := (pu.date + make_interval(months => k))::date;
        insert into public.pop_installments (purchase_id, customer_id, agent_id, seq, due_date, amount, status, note)
        values (p_purchase, v_cust, v_agent, k, v_due, tm.monthly,
                case when v_due < date '2026-10-01' then 'assumed' when v_due < v_today then 'auto' else 'due' end,
                case when v_due < date '2026-10-01' then 'before tracking began' end);
        v_n := v_n + 1;
    end loop;
    return v_n;
exception when others then
    return 0;
end $$;
revoke all on function public.pop_plan_sync(bigint) from public, anon, authenticated;

-- ── summary (board tiles) + profile line ────────────────────────────────────
drop function if exists public.pop_summary();
create or replace function public.pop_summary()
returns table (outstanding numeric, plans integer, lapsed_rm numeric, lapsed_n integer,
               receipts_n integer, receipts_rm numeric, to_come numeric, due_90 numeric,
               overdue_n integer, due_month numeric, due_month_n integer)
language sql stable security definer set search_path = public as $$
    with t as (select (now() at time zone 'Asia/Kuala_Lumpur')::date d),
    s as (select i.* from public.pop_installments i
           where i.agent_id in (select public.pop_scope_ids())
              or (coalesce(public.current_user_level(), 99) <= 2 and i.agent_id is null)),
    r as (select x.* from public.pop_receipts x
           where x.agent_id in (select public.pop_scope_ids())
              or (coalesce(public.current_user_level(), 99) <= 2 and x.agent_id is null))
    select coalesce(sum(s.amount) filter (where s.status in ('due', 'lapsed')), 0),
           count(distinct s.purchase_id) filter (where s.status in ('due', 'lapsed'))::int,
           coalesce(sum(s.amount) filter (where s.status = 'lapsed'), 0),
           (count(*) filter (where s.status = 'lapsed'))::int,
           (select count(*) from r cross join t where date_trunc('month', r.paid_date) = date_trunc('month', t.d))::int,
           (select coalesce(sum(r.amount), 0) from r cross join t where date_trunc('month', r.paid_date) = date_trunc('month', t.d)),
           coalesce(sum(s.amount) filter (where s.status = 'due'), 0),
           coalesce(sum(s.amount) filter (where s.status = 'due' and s.due_date <= t.d + 90), 0),
           (count(*) filter (where s.status = 'lapsed'))::int,
           coalesce(sum(s.amount) filter (where s.status in ('due', 'auto') and date_trunc('month', s.due_date) = date_trunc('month', t.d)), 0),
           (count(*) filter (where s.status in ('due', 'auto') and date_trunc('month', s.due_date) = date_trunc('month', t.d)))::int
      from t left join s on true group by t.d
$$;
revoke all on function public.pop_summary() from public, anon;
grant execute on function public.pop_summary() to authenticated;

create or replace function public.pop_person_plans(p_pid bigint)
returns table (purchase_id bigint, item text, total integer, done integer, left_rm numeric,
               next_due date, next_amount numeric, failed integer, monthly numeric)
language plpgsql stable security definer set search_path = public as $$
declare v_cid bigint;
begin
    select c.id into v_cid from public.customers c where c.converted_from_prospect_id = p_pid order by c.id limit 1;
    if v_cid is null or not (public.customer_is_visible(v_cid) or public.prospect_is_visible(p_pid)) then return; end if;
    return query
    select i.purchase_id, max(pu.item), count(*)::int,
           (count(*) filter (where i.status in ('auto', 'assumed', 'paid_manual', 'waived')))::int,
           coalesce(sum(i.amount) filter (where i.status in ('due', 'lapsed')), 0),
           min(i.due_date) filter (where i.status = 'due'),
           (array_agg(i.amount order by i.due_date) filter (where i.status = 'due'))[1],
           (count(*) filter (where i.status = 'lapsed'))::int,
           max(i.amount)
      from public.pop_installments i join public.purchases pu on pu.id = i.purchase_id
     where i.customer_id = v_cid
     group by i.purchase_id
     order by min(i.due_date) filter (where i.status = 'due') nulls last;
end $$;
revoke all on function public.pop_person_plans(bigint) from public, anon;
grant execute on function public.pop_person_plans(bigint) to authenticated;

-- ── daily 08:30 MYT: past charges → auto · lapse reminders every 3 days ──────
create or replace function public.pop_daily() returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_today date := (now() at time zone 'Asia/Kuala_Lumpur')::date; v_n int;
begin
    update public.pop_installments set status = 'auto' where status = 'due' and due_date < v_today;
    insert into public.notification_outbox (user_id, kind, priority, title, body, url, dedupe_key, due_at)
    select i.agent_id, 'pop_lapsed', 'normal',
           '💳 POP lapsed — ' || coalesce(c.full_name, 'customer'),
           'RM' || round(i.amount) || ' (' || to_char(i.due_date, 'FMMon YYYY') || ') · marked ' || (v_today - i.lapsed_at)
             || ' days ago · collect the bank-in receipt and upload it',
           './index.html?pop=1#pipeline', 'pop_lapsed:' || i.id || ':' || v_today, now()
      from public.pop_installments i
      left join public.customers c on c.id = i.customer_id
     where i.status = 'lapsed' and i.agent_id is not null and i.lapsed_at < v_today
       and (v_today - i.lapsed_at) % 3 = 0
    on conflict (user_id, dedupe_key) do nothing;
    get diagnostics v_n = row_count;
    return v_n;
end $$;
revoke all on function public.pop_daily() from public, anon, authenticated;
select cron.unschedule('pop-month-push') where exists (select 1 from cron.job where jobname = 'pop-month-push');
select cron.unschedule('pop-daily') where exists (select 1 from cron.job where jobname = 'pop-daily');
select cron.schedule('pop-daily', '30 0 * * *', 'select public.pop_daily();');

-- ── 📋 top 5: lapsed charges only (redefines the to-do function) ────────────
create or replace function public.journey_todo_for(p_uid bigint, p_limit integer default 5)
returns table (kind text, icon text, prospect_id bigint, customer_id bigint, name text, why text, rm numeric, due date, score numeric, ref_id bigint)
language sql stable security definer set search_path = public as $$
with t as (select public.journey_today() d),
c as (   -- ① collections: ready ≤ 7 days, not handed over
    select 'collect'::text kind, '📦'::text icon, cu.converted_from_prospect_id pid, cu.id cid, cu.full_name nm,
           case when di.expected_ready_date < t.d then 'Collect ' || left(di.item_name, 30) || ' · ready since ' || to_char(di.expected_ready_date, 'FMDD Mon')
                else 'Ready ' || to_char(di.expected_ready_date, 'FMDD Mon') || ' · book the collection + photo' end why,
           coalesce(pu.amount, 10000) rm, di.expected_ready_date due,
           greatest(coalesce(pu.amount, 10000), 3000) * case when di.expected_ready_date < t.d then 3 else 2 end
             * (1 + least(greatest(t.d - di.expected_ready_date, 0), 30) / 30.0) sc, di.purchase_id ref
      from public.delivery_items di cross join t
      join public.customers cu on cu.id = di.customer_id
      left join public.purchases pu on pu.id = di.purchase_id
     where di.status = 'pending' and di.expected_ready_date <= t.d + 7
       and di.expected_ready_date >= t.d - 120
       and coalesce(pu.agent_id, cu.responsible_agent_id) = p_uid
),
g as (   -- ② Golden Road session due
    select 'gr', '🟣', coalesce(tp.prospect_id, cu.converted_from_prospect_id), tp.customer_id, coalesce(cu.full_name, pr.full_name),
           'Golden Road ' || tp.seq || '/' || tp.seq_total || case when tp.due_date < t.d then ' · overdue' else ' · due ' || to_char(tp.due_date, 'FMDD Mon') end,
           coalesce(pu.amount, 10000), tp.due_date,
           greatest(coalesce(pu.amount, 10000), 3000) * 2 * (1 + least(greatest(t.d - tp.due_date, 0), 30) / 30.0), tp.purchase_id
      from public.journey_touchpoints tp cross join t
      left join public.customers cu on cu.id = tp.customer_id
      left join public.prospects pr on pr.id = tp.prospect_id
      left join public.purchases pu on pu.id = tp.purchase_id
     where tp.status = 'pending' and tp.seq is not null and tp.assigned_to_id = p_uid and tp.due_date <= t.d + 3
       and coalesce(tp.snooze_until, t.d) <= t.d
),
cps as ( -- ③ CPS with no 2nd meeting (A)
    select 'cps', '🆕', p.id, null::bigint, p.full_name,
           'CPS ' || to_char(x.d, 'FMDD Mon') || ' · no 2nd meeting booked',
           coalesce(nullif(p.open_potential_rm, 0), 5000), x.d,
           greatest(coalesce(p.open_potential_rm, 0), 5000) * 1.5 * case when t.d - x.d <= 14 then 1.2 else 0.8 end, null::bigint
      from public.prospects p cross join t
      cross join lateral (select max(a.activity_date) d from public.activities a where a.prospect_id = p.id and a.activity_type = 'CPS') x
     where p.responsible_agent_id = p_uid and x.d between t.d - 30 and t.d - 1
       and coalesce(p.status, '') not in ('converted', 'lost') and not coalesce(p.unable_to_serve, false)
       and coalesce(p.manual_grade, '') <> 'F' and coalesce(p.cps_next_step, '') <> 'not_interested'
       and not exists (select 1 from public.activities a where a.prospect_id = p.id and a.activity_date > x.d
                         and a.activity_type in ('CPS', 'FTF', 'FSA', 'SITE', 'GR', 'EVENT', 'EVENT_CLOSING'))
       and not exists (select 1 from public.event_attendees ea where ea.attendee_type = 'prospect' and ea.entity_id = p.id
                         and ea.created_at::date >= x.d)
),
hot as ( -- ④ Commit / Audit / Hot with nothing booked
    select 'book', case p.potential_tier when 'commit' then '🟢' when 'audit' then '🩺' else '🔥' end, p.id, null::bigint, p.full_name,
           initcap(p.potential_tier) || ' · RM' || round(p.open_potential_rm / 1000) || 'k · nothing booked'
             || coalesce(' · met ' || to_char(p.potential_last_met, 'FMDD Mon'), ''),
           p.open_potential_rm, p.potential_last_met,
           p.open_potential_rm * case p.potential_tier when 'commit' then 3 when 'audit' then 2 else 1.5 end
             * (1 + least(coalesce(t.d - p.potential_last_met, 60), 60) / 60.0), null::bigint
      from public.prospects p cross join t
     where p.responsible_agent_id = p_uid and p.potential_tier in ('commit', 'audit', 'hot')
       and p.potential_next_booked is null and p.open_potential_rm > 0
),
tp as (  -- ⑤ any other journey step due today or overdue
    select 'touch', '🧭', coalesce(j.prospect_id, cu.converted_from_prospect_id), j.customer_id, coalesce(cu.full_name, pr.full_name),
           regexp_replace(j.title, '^\S+\s+', '') || case when j.due_date < t.d then ' · overdue' else '' end,
           coalesce(nullif(pr.open_potential_rm, 0), 3000), j.due_date,
           greatest(coalesce(pr.open_potential_rm, 0), 3000) * case when j.priority = 'high' then 1.2 else 1 end
             * (1 + least(greatest(t.d - j.due_date, 0), 30) / 30.0), j.id
      from public.journey_touchpoints j cross join t
      left join public.customers cu on cu.id = j.customer_id
      left join public.prospects pr on pr.id = j.prospect_id
     where j.status = 'pending' and j.seq is null and j.assigned_to_id = p_uid and j.due_date <= t.d
       and j.due_date >= t.d - 60 and coalesce(j.snooze_until, t.d) <= t.d
